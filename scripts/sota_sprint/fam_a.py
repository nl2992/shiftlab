"""SOTA sprint family A: dependence-aware certification (candidates A1-A6).

All candidates keep QSG's decision skeleton (incumbent 0 vs frozen challenger 1; promote test,
discard test, mirrored rollback test; cycle j of promotion runs at alpha / 2^j) and change one or
more of: the evidence process, the acquisition density, the clock semantics.

Observation model and filtration
--------------------------------
Queried disagreement outcomes ``z_k = 1[challenger correct]`` are processed in query (= issue
event) order; with the common simulator's constant delay, release order equals issue order. Write
``t_k`` for the issue event of query k and ``g_k = t_k - t_{k-1}``. ``F_{k-1}`` is generated by
``(z_i, t_i)_{i<k}``, the disagreement indicators and the policy's private randomness. The query
decision at ``t_k`` uses only labels released before ``t_k`` (a subset of ``F_{k-1}``),
disagreement indicators (independent of the sign process) and private randomness, so the issue
time ``t_k`` is predictable and the sign at ``t_k`` is not read before issue.

Declared null class (A1, A5, A6). ``H+``: the event-time sign process ``s_t`` (``z_k = s_{t_k}``)
is a stationary two-state Markov chain with ``P(s=1) = p <= 1/2`` and persistence
``rho in [0, 1]`` (at each event it keeps its value w.p. rho, else redraws Bernoulli(p)), and is
independent of the disagreement process. NO bound on rho is declared. Then
``P(z_k = 1 | F_{k-1}) = a_k z_{k-1} + (1 - a_k) p`` with ``a_k = rho^{g_k}``, and
``P(z_1 = 1) = p``. ``H-`` mirrors it (``p >= 1/2``) for the discard and rollback tests.

A1 evidence: sequential universal inference (Wasserman, Ramdas & Balakrishnan 2020, Sec. 7).
For a start index j, ``R_{j,k} = Q_{j:k} / U_{j:k}`` where ``Q`` is a mixture over alternative
Markov models (p' > 1/2, rho' in a grid) of the conditional likelihood of ``z_j..z_k`` given
``z_{j-1}`` and the gaps, and ``U_{j:k}`` is a rigorous UPPER bound on
``sup_{(p,rho) in H+} L_{p,rho}(z_j..z_k | z_{j-1}, gaps)``. Because ``U >= L_theta`` for the true
null member theta, ``R_{j,k} <= Q_{j:k} / L_theta(j:k)``, a nonnegative martingale from j with
mean 1. Started mixture ``E_k = sum_m w_m R_{s_m,k}`` over sparse starts ``s_m`` with
``sum w_m = 1``; ``E_k + sum_{s_m > k} w_m`` is dominated by a test supermartingale, and Ville
gives ``P(sup_k E_k >= 1/a) <= a`` under every member of H+ simultaneously.

The upper bound U: partition [0,1/2] x [0,1] into (p, rho) cells. On a cell each one-step factor
is monotone in p and in rho separately (``P(+|+) = a + (1-a)p`` increasing in both;
``P(-|+) = (1-a)(1-p)`` decreasing in both; ``P(+|-) = (1-a)p`` increasing in p, decreasing in
rho; ``P(-|-) = 1 - (1-a)p`` decreasing in p, increasing in rho), so its cell maximum is at a known
corner. The product of per-factor cell maxima bounds the cell sup; the max over cells bounds the
null sup. No grid point is ever used as a proxy for the sup, so a coarse grid is conservative,
never anti-conservative.

A4 evidence: post-unfavourable transition betting. Under H+ (any rho),
``P(z_k = 1 | z_{k-1} = 0, F_{k-1}) = (1 - a_k) p <= 1/2``, so a QSG started-mixture factor applied
only to outcomes whose previous queried outcome was 0 (and to the very first outcome) has
conditional mean <= 1; other outcomes contribute factor 1. Valid with no rho bound.

A2 acquisition: adaptive evidence density. While front-loading, a disagreement at event t is
queried only if the event gap since the last ISSUED query is at least
``g* = min{g : rho_hat^g <= c}`` where ``rho_hat`` is the gap-indexed Markov MLE from released
outcomes (p profiled). Deterministic and predictable: depends only on released labels and issue
times. A2 alone keeps QSG's iid evidence (empirically screened, NOT certified under dependence);
A5 pairs it with A1's evidence.

A3 dual-clock. (i) Segment semantics: after a verdict, QSG starts the new test at the RELEASE time
of the verdict and discards every outcome issued in the preceding ``delay`` events. A3 starts the
new test at the next outcome in query order (all in-flight outcomes are used); each new test is a
fresh e-process from that index, conditional on the past, so validity is unchanged. (ii) In-flight
awareness: front-loading pauses (falls back to paced monitoring) while the number of issued but
unreleased queries already exceeds a margin times the projected number of further outcomes the
current test needs (projection from the running mean; predictable).
"""

