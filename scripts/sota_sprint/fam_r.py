class RGate(fam_d.DeployGate):
    """D2 (CAMS host + deploy gate) with pluggable evidence/rule; see module docstring.

    evidence: "sm" | "cmi" | "cmq" | "mk" | "both" | "comb" | "econ"
    q_floor : gate query probability on undecided disagreements when the host does NOT rank the
              challenger first (D2: 0). Acquisition parameter for R6; also lowers IPW variance.
    """

    Z_COMPS = ("sm", "cmq", "mk")

    def __init__(
        self,
        host,
        T,
        B,
        alpha,
        *,
        rng,
        evidence="sm",
        mk_kw=None,
        lams=LAMS,
        q_floor=0.0,
        acq="host_pref",
        kappa=None,
        var_adj=True,
        min_obs=10,
        cs=5.0,
        name="RGate",
    ):
        self.evidence, self.mk_kw, self.lams = evidence, dict(mk_kw or {}), lams
        self.q_floor = float(q_floor)
        self.comps = {
            "sm": ("sm",),
            "cmi": ("cmi",),
            "cmq": ("cmq",),
            "mk": ("mk",),
            "both": ("cmi", "mk"),
            "comb": ("cmi", "mk"),
            "econ": (),
        }[evidence]
        self.latched: dict[str, bool] = {}
        self.ipw_q: list[list] = []  # ordered queue of undecided-phase disagreements
        self.kappa = _norm_ppf(1.0 - alpha) if kappa is None else float(kappa)
        self.var_adj, self.min_obs, self.cs = var_adj, int(min_obs), float(cs)
        self.n_dis = 0
        self.t_now = 0
        self.ez: list[int] = []
        self.et: list[int] = []
        self.rho_hat = 0.0
        super().__init__(
            host,
            T,
            B,
            alpha,
            rng=rng,
            cert=fam_d.started_mixture,
            acq=acq,
            and_host=True,
            rollback=False,
            name=name,
        )

    # -- evidence objects ---------------------------------------------------------------------
    def _mk(self, kind, side):
        if kind == "sm":
            return fam_d._Cert(side)
        if kind == "cmq":
            return _QCCert(side, self.lams)
        if kind == "cmi":
            return CondMeanEP(self.lams)
        if kind == "mk":
            return markov_cert(**self.mk_kw)(side)
        raise ValueError(kind)

    def _new_tests(self):
        self.ev = {c: (self._mk(c, +1), self._mk(c, -1)) for c in getattr(self, "comps", ())}
        self.latched = {c: False for c in getattr(self, "comps", ())}
        self.cert_ok = False

    def ev_value(self, comp, side=+1) -> float:
        o = self.ev[comp][0 if side > 0 else 1]
        return float(getattr(o, "m", o).value)

    # -- deployment ---------------------------------------------------------------------------
    def predict(self, event):
        self.t_now = event.t
        if self.evidence == "econ" and self.deployed == 0:
            v, v_ucb = self.econ_value(event.t)
            self.cert_ok = v > 0  # re-evaluated every event (a plug-in rule, not a latched test)
            if v > 0 or v_ucb < 0:
                self.decided = True  # economically settled: stop gate front-loading
        return super().predict(event)

    # -- acquisition (D2's rule; records the issue-time propensity of EVERY disagreement) --------
    def request_labels(self, event, remaining_budget):
        dis = bool(event.model_predictions[0] != event.model_predictions[1])
        self.pacer.propensity(event.t, remaining_budget, dis)  # keeps D2's pacer state
        self.pacer.note_event(dis)
        if dis:
            self.n_dis += 1
        hreq = self.host.request_labels(event, remaining_budget)
        final = self.deployed == 1 and self.stop_when_final
        if final or not dis:
            return QueryRequest(requested=False)
        pre = self.deployed == 0
        if remaining_budget <= 0 or (pre and remaining_budget <= self.reserve):
            if pre:
                self.ipw_q.append([event.t, 0.0, False, None])  # unidentifiable: freezes cmi
            return QueryRequest(requested=False)
        u = fam_d._host_u(self.host, event, hreq)
        if (
            pre
            and not self.decided
            and (self.acq == "always" or (self.acq == "host_pref" and self.host_pref == 1))
        ):
            q_g = 1.0
        elif pre and not self.decided:
            q_g = self.q_floor
        else:
            q_g = 0.0
        take = bool(hreq.requested) or (q_g > 0 and bool(self.rng.random() < q_g))
        q_comb = u + (1.0 - u) * q_g
        if pre:
            self.ipw_q.append([event.t, q_comb, take, None])
        if not take:
            return QueryRequest(requested=False)
        extra = dict(hreq.extra) if hreq.requested else fam_d._host_extra(self.host, event)
        self._req[event.t] = (bool(hreq.requested), u, q_comb)
        return QueryRequest(requested=True, probability=q_comb, extra=extra)

    # -- feedback ------------------------------------------------------------------------------
    def observe(self, feedback):
        fbs = sorted(feedback, key=lambda f: f.event_id)
        host_fb = []
        for fb in fbs:
            _drew, _u, q_comb = self._req.pop(
                fb.event_id, (True, fb.query_probability, fb.query_probability)
            )
            host_fb.append(
                ReleasedFeedback(
                    fb.event_id,
                    fb.t_requested,
                    fb.t_released,
                    fb.label,
                    fb.model_losses,
                    float(q_comb),
                    fb.extra,
                )
            )
        if host_fb:
            self.host.observe(host_fb)
        res = {}
        for fb in fbs:
            d = int(fb.model_losses[0]) - int(fb.model_losses[1])
            if d == 0:
                continue
            z, last = int(d > 0), self.last
            self.last = (z, fb.event_id)
            self.ez.append(z)
            self.et.append(fb.event_id)
            res[fb.event_id] = z
            if self.deployed != 0:
                continue
            for c in self.comps:
                if c in self.Z_COMPS:
                    self.ev[c][0].update(z, fb.event_id, last)
                    self.ev[c][1].update(z, fb.event_id, last)
        if self.deployed == 0 and "cmi" in self.comps:
            self._flush_ipw(res)
        if self.evidence == "econ" and len(self.ez) >= 9 and len(self.ez) % 5 == 0:
            r = fam_a.rho_mle(np.array(self.ez[-150:]), np.array(self.et[-150:]), sig=2.0)
            self.rho_hat = 0.0 if r is None else r
        if self.deployed == 0 and self.comps:
            self._decide()

    def _flush_ipw(self, res):
        for item in self.ipw_q:
            if item[2] and item[0] in res:
                item[3] = res[item[0]]
        up, dn = self.ev["cmi"]
        i = 0
        while i < len(self.ipw_q):
            _t, q, taken, r = self.ipw_q[i]
            if q <= 0.0:
                up.frozen = dn.frozen = True
                i = len(self.ipw_q)
                break
            if taken and r is None:
                break
            if taken:
                up.update(r / q)
                dn.update((1 - r) / q)
            else:
                up.update(0.0)
                dn.update(0.0)
            i += 1
        del self.ipw_q[:i]
        if up.frozen:
            self.ipw_q.clear()

    def _decide(self):
        thr = 2.0**self.cycle / self.alpha
        for c in self.comps:
            if self.ev_value(c, +1) >= thr:
                self.latched[c] = True  # Ville bounds "ever crossed" for each e-process
        if self.evidence == "comb":
            e = 0.5 * (self.ev_value("cmi") + self.ev_value("mk"))
            ok = e >= thr
        else:
            ok = all(self.latched[c] for c in self.comps)
        if ok:
            self.cert_ok, self.decided = True, True
        elif not self.cert_ok and any(self.ev_value(c, -1) >= 1.0 / self.alpha for c in self.comps):
            self.decided = True  # discard: stop gate front-loading, host continues

    # -- R5 economic value -----------------------------------------------------------------------
    def econ_value(self, t):
        n = len(self.ez)
        if n < self.min_obs:
            return -1.0, 1.0
        n1 = sum(self.ez)
        a, b = 1.0 + n1, 1.0 + n - n1
        ph = a / (a + b)
        sd = math.sqrt(a * b / ((a + b) ** 2 * (a + b + 1)))
        if self.var_adj and self.rho_hat > 0 and n >= 2:
            g = float(np.median(np.diff(self.et[-150:]))) if n > 1 else 1.0
            ar = self.rho_hat ** max(g, 1.0)
            sd *= math.sqrt((1 + ar) / max(1 - ar, 1e-3))
        dh = self.n_dis / max(t, 1)
        rem = max(self.T - t, 0)
        gain = rem * dh * (2 * ph - 1)
        pen = self.kappa * rem * dh * 2 * sd
        return gain - self.cs - pen, gain - self.cs + pen

    def decision_state(self):
        return f"dep={self.deployed};cert={int(self.cert_ok)};pref={self.host_pref}"


def _norm_ppf(p):
    from statistics import NormalDist

    return NormalDist().inv_cdf(min(max(p, 1e-9), 1 - 1e-9))


