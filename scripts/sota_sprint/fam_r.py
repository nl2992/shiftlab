    def table(df):
        df = df[df.policy.isin(configs)]
        risk = df[df.regime.isin(RISK_NULLS)].groupby(["policy", "alpha"]).ever_promote.mean()
        cost = df[df.regime.isin(RISK_ALTS)].groupby(["policy", "alpha"]).net.mean()
        return risk, cost

    rd, cd = table(dev)
    out = {}
    for t, v in RISK_TARGETS.items():
        ok = rd[rd <= v].index
        if not len(ok):
            out[t] = None
            continue
        p, a = min(ok, key=lambda k: cd.get(k, np.inf))
        g = ev[(ev.policy == p) & np.isclose(ev.alpha, a)]
        gn, ga = g[g.regime.isin(RISK_NULLS)], g[g.regime.isin(RISK_ALTS)]
        k, n = int(gn.ever_promote.sum()), len(gn)
        out[t] = {
            "config": p,
            "alpha": float(a),
            "dev_risk": float(rd[(p, a)]),
            "dev_cost": float(cd[(p, a)]),
            "eval_risk": k / max(n, 1),
            "eval_risk_ci": wilson(k, n),
            "eval_cost": float(ga.net.mean()),
        }
    return out


