"""Sprint 2 Family R: risk-adjusted decision architectures on the D2 deploy gate (R1-R6).

Every policy here is ``fam_d.DeployGate`` on the CAMS host (constant policies) with D2's
acquisition (the gate front-loads every disagreement while undecided and the host ranks the
challenger first; the host keeps its own CAMS queries) and D2's deployment rule (promote when the
evidence has crossed and the host ranks the challenger first; promotion is absorbing, no
rollback). What changes is the EVIDENCE that gates promotion (R2-R4), the promotion RULE
(R5, economic), or the ACQUISITION parameters chosen jointly with alpha (R6). R1 is D2 itself run
on the alpha grid.

Filtration. Events are processed in issue order through an ordered queue (release order equals
issue order because the delay is constant). ``G_{k-1}`` is generated by the predictions of events
``<= k``, every query coin of events ``< k`` and the labels of the QUERIED events ``< k``. The
query propensity of event k, ``q_k = u_k + (1 - u_k) q_gate_k`` (two independent coins: CAMS's own
draw with probability ``u_k`` and the gate's), is computed at issue from labels released before
issue (a sub-sigma-field of ``G_{k-1}``), the predictions of event k and the remaining budget; it
never reads the label of event k. Disagreement is predictions-measurable. ``d_k = l0_k - l1_k`` is
0 on an agreement (known for free) and +-1 on a disagreement; ``r_k = 1[d_k > 0]``.

Evidence components (each tests ONE stated null; see docs/sprint2/family_r/):

* ``sm``  QSG started mixture on query-conditional ``z`` (D2's own evidence). Null: POINTWISE
  query-conditional ``P(z_k = 1 | G_{k-1}, queried disagreement) <= 1/2`` for every k (V1, strong).
* ``cmi`` (R2) time-averaged conditional-mean e-process on ALL events with IPW. Increment
  ``Y_k = 1/2`` on an agreement, ``Y_k = L_k r_k / q_k`` on a disagreement (``L_k`` = queried).
  ``Y_k >= 0`` and ``E[Y_k | G_{k-1}] = v_k = 1/2 + mu_k / 2`` with ``mu_k = E[d_k | G_{k-1}]``.
  E-process: ``E_t = sum_j pi_j prod_{k<=t} (1 + lam_j (Y_k - 1/2))`` over a FIXED grid
  ``lam_j in (0, 2)`` (no predictable bet, no started mixture). Null (V1, weak):
  ``H_CM: sum_{k<=t} mu_k <= 0 for every t`` (pathwise), i.e. the running average of the
  conditional mean paired loss difference over all events never favours the challenger. Lemma:
  ``M_t(lam) = prod (1 + lam (Y_k - 1/2)) / prod (1 + lam (v_k - 1/2))`` is a positive martingale
  (``1 + lam (v_k - 1/2) >= 1 - lam/2 > 0``), and by concavity of log
  ``sum log(1 + lam a_k) <= t log(1 + lam abar_t) <= 0`` whenever ``abar_t <= 0``, so
  ``prod (1 + lam (Y_k - 1/2)) <= M_t(lam)`` for every t under H_CM; Ville gives
  ``P(sup_t E_t >= 1/a) <= a``. Weights may be unbounded (``Y >= 0`` keeps wealth positive for
  every ``lam < 2``; cf. Waudby-Smith et al. 2022). The test is STOPPED (frozen) at the first
  disagreement with ``q_k = 0`` (budget exhausted, or CAMS u = 0 with no gate query): there the
  difference is not identifiable, and a frozen e-process is still Ville-bounded.
* ``cmq`` (R2 ablation) the same fixed-lam product on query-conditional ``z``: null (V1, weak,
  query-conditional) ``sum_{n<=m} (P(z_n = 1 | G_{n-1}, queried) - 1/2) <= 0`` for every m.
* ``mk`` (R3) fam_a.MarkovSUI (gap-aware Markov sequential universal inference) or a variant with
  an extra predictable plug-in numerator / tilted (p, rho) prior / other start allocation. Null
  (V2): stationary first-order Markov sign chain in event time with p <= 1/2, any rho. The
  denominator (cell upper bound on the null sup) is never changed; numerators are mixtures of
  predictable predictive distributions, so ``Q / U <= Q / L_theta`` stays a test martingale.

Combinations (R4): ``both`` latches each e-process separately and promotes only when both have
crossed ``2/alpha`` (false promotion <= alpha under H_CM, and <= alpha under the Markov null,
separately). ``comb`` promotes when ``(E_cmi + E_mk)/2 >= 2/alpha``: valid only under the
INTERSECTION of the two nulls; its alpha is risk-calibrated on development nulls (Track R).

R5 economic rule: promote when (host agrees and) ``V_t = (T - t) dhat (2 phat - 1) - c_s -
kappa (T - t) dhat 2 sd_t > 0`` with ``phat`` the Beta(1,1) posterior mean of query-conditional
``z``, ``dhat`` the running disagreement rate, ``sd_t`` the posterior sd inflated by the Markov
variance factor ``(1 + a)/(1 - a)`` (``a`` = shrunk gap-indexed persistence MLE to the power of
the median observed gap) and ``kappa = Phi^{-1}(1 - alpha)``. Null V3 (economic non-improvement);
NO anytime guarantee.
"""

