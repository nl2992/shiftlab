# ------------------------------------------------------------------------------------------------
# R2: fixed-lambda conditional-mean e-process (weak, time-averaged conditional-mean null)
# ------------------------------------------------------------------------------------------------
class CondMeanEP:
    """``E_t = mean_j prod_k (1 + lam_j (Y_k - 1/2))`` for nonnegative ``Y`` (null mean <= 1/2)."""

    def __init__(self, lams=LAMS):
        self.lams = np.asarray(lams, float)
        if not np.all((self.lams > 0) & (self.lams < 2)):
            raise ValueError("lam must lie in (0, 2) so that 1 - lam/2 > 0")
        self.logw = np.zeros(len(self.lams))
        self.n = 0
        self.frozen = False

    def update(self, y: float) -> float:
        if self.frozen:
            return self.value
        if y < 0:
            raise ValueError("Y must be >= 0")
        self.n += 1
        self.logw += np.log1p(self.lams * (y - 0.5))
        return self.value

    @property
    def log_value(self) -> float:
        m = float(self.logw.max())
        return m + math.log(float(np.mean(np.exp(self.logw - m))))

    @property
    def value(self) -> float:
        return float(math.exp(min(self.log_value, 700.0)))


