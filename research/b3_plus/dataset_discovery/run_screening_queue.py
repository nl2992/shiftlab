"""Drive the B3+ screening queue. Resumable; a finished dataset is never re-screened.

    uv run python research/b3_plus/dataset_discovery/run_screening_queue.py --resume
    ... --only trec07            screen one candidate (refused if it already has a final status)
    ... --max-candidates 3       screen at most 3 queued candidates this invocation
    ... --report-only            regenerate successful_cases.json / discarded_cases.json / summary.md

Stops when ``--target-successes`` (default 2) NEW SUCCESS cases exist or the queue is exhausted.
"A failed dataset is not retried with different settings": --only on a finished dataset exits.
"""

from __future__ import annotations

import argparse
import json
import sys
import traceback
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import download_datasets as dl
import registry as reg
import screen_candidate as sc

FINAL = {
    "SUCCESS",
    "USELESS_INELIGIBLE",
    "USELESS_NO_HEADROOM",
    "USELESS_NO_IMPROVEMENT",
    "USELESS_UNSTABLE",
    "USELESS_DATA_QUALITY",
    "USELESS_DUPLICATE",
    "NOT_RUN",
}
EXISTING = [
    ("spam", "SUCCESS", "-6.66 (P7s vs P3b), 247.43 < 849.00", "K=1 LOW-POWER"),
    ("rialto", "SUCCESS", "-5.31, 98.42 < 202.06", "K=16"),
    ("weather", "SUCCESS", "-3.20, 472.57 < 504.00", "K=3 LOW-POWER"),
    ("airlines", "USELESS_NO_HEADROOM", "-0.56, 780.84 > 776.80", "K=50"),
    ("bank", "USELESS_NO_HEADROOM", "-0.57, 427.61 > 419.38", "K=8"),
    ("elec2", "USELESS_NO_HEADROOM", "-0.06, 397.52 > 389.50", "K=4"),
    ("criteo", "USELESS_NO_HEADROOM", "-0.04, 699.16 > 693.92", "K=50"),
]


def n_new_success(registry) -> int:
    return sum(e["status"] == "SUCCESS" for e in registry["candidates"])


def screening_record(e: dict) -> dict:
    s = e.get("screening") or {}
    return {
        "dataset_id": e["dataset_id"],
        "family": e["family"],
        "source": e["source"],
        "url": e["url"],
        "domain": e["domain"],
        "n_rows": e["n_rows"],
        "declared_delay": e["declared_delay"],
        "chronology": e["chronology"],
        "status": e["status"],
        "status_reason": e["status_reason"],
        "overlap_note": e.get("overlap_note"),
        "timestamps": e["timestamps"],
        "screening": s,
        "results_dir": f"docs/promising_directions/results/b3_plus/screening/{e['dataset_id']}",
    }


def write_reports(registry: dict) -> None:
    cands = list(registry["candidates"])
    ok = [screening_record(e) for e in cands if e["status"] == "SUCCESS"]
    bad = [screening_record(e) for e in cands if e["status"] not in ("SUCCESS", "QUEUED")]
    queued = [e["dataset_id"] for e in cands if e["status"] == "QUEUED"]
    (HERE / "successful_cases.json").write_text(
        json.dumps(ok, indent=2, default=str), encoding="utf-8"
    )
    (HERE / "discarded_cases.json").write_text(
        json.dumps(bad, indent=2, default=str), encoding="utf-8"
    )

    # ---- markdown ----------------------------------------------------------------------
    def cnt(pred):
        return sum(1 for e in cands if pred(e))

    n_screened = cnt(lambda e: e["status"] not in ("QUEUED", "NOT_RUN", "USELESS_DUPLICATE"))
    n_dup = cnt(lambda e: e["status"] == "USELESS_DUPLICATE")
    n_not_run = cnt(lambda e: e["status"] == "NOT_RUN")
    n_eval = cnt(lambda e: (e.get("screening") or {}).get("stage") == "evaluated")
    lines = [
        "# B3+ dataset screening summary",
        "",
        (
            "Generated by `run_screening_queue.py` from `dataset_registry.json`. Protocol: "
            f"`{reg.PROTOCOL}` (frozen). Method P7s, T=2000, B=200, c_q=0.05, c_s=5, 100 seeds, "
            "seed base 20261101. No parameter was tuned per dataset."
        ),
        "",
        "## Denominator (protocol section 5)",
        "",
        f"- Candidates registered in this screening: {len(cands)}",
        f"- Actually screened (reached validation): {n_screened}",
        f"- Reached locked-window evaluation (passed eligibility and the dev headroom precheck): {n_eval}",
        f"- New SUCCESS cases: {n_new_success(registry)}",
        f"- USELESS_DUPLICATE (not screened, family already represented): {n_dup}",
        f"- NOT_RUN (skipped with recorded reason): {n_not_run}",
        f"- Still queued: {len(queued)} {queued}",
        "",
        "Five-case set already in hand before this screening: spam, rialto, weather (3 of 5).",
        (
            "Selection uses locked-window outcomes, so these are a selected set, not an unbiased "
            "success rate."
        ),
        "",
        "## Per-candidate outcome",
        "",
        "| dataset | source | delay | outcome | status | detail |",
        "|---|---|---:|---|---|---|",
    ]
    for e in sorted(cands, key=lambda e: (e["queue_rank"], e["dataset_id"])):
        s = e.get("screening") or {}
        stage = s.get("stage", "-")
        det = (e["status_reason"] or "").replace("|", "/")
        lines.append(
            f"| {e['dataset_id']} | {e['source'].split(' ')[0]} | {e['declared_delay']['value']} "
            f"| {stage} | {e['status']} | {det[:300]} |"
        )
    lines += ["", "## Evaluated candidates (locked window)", ""]
    for e in cands:
        s = e.get("screening") or {}
        if s.get("stage") != "evaluated":
            continue
        mc, pd_ = s["mean_cost"], s["paired"]["P7s_minus_P3b"]
        lines.append(
            f"- **{e['dataset_id']}**: K={s['episodes']}; P0 {mc['P0']:.2f}, P2 {mc['P2']:.2f}, "
            f"P3b {mc['P3b']:.2f}, P6 {mc['P6']:.2f}, P7s {mc['P7s']:.2f} (P1 hindsight {mc['P1']:.2f}); "
            f"P7s-P3b {pd_['mean']:+.3f} [{pd_['lo']:+.3f}, {pd_['hi']:+.3f}] "
            f"({pd_['bootstrap_level']} bootstrap{', LOW-POWER' if s['low_power'] else ''}); "
            f"status **{e['status']}**."
        )
    lines += ["", "## Programme streams screened earlier (protocol section 6)", ""]
    lines += ["| stream | P7s vs P3b / P7s vs P0 | episodes | status |", "|---|---|---|---|"]
    lines += [f"| {a} | {c} | {d} | {b} |" for a, b, c, d in EXISTING]
    (HERE / "screening_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def run(args) -> int:
    registry = reg.init_registry()
    ids = [
        e["dataset_id"]
        for e in sorted(registry["candidates"], key=lambda e: e["queue_rank"])
        if e["queue_rank"] != 0
    ]
    if args.only:
        if args.only not in ids:
            raise SystemExit(f"unknown dataset '{args.only}'")
        e = reg.get(registry, args.only)
        if e["status"] in FINAL:
            raise SystemExit(
                f"{args.only} already has final status {e['status']}; the protocol forbids "
                "re-screening a finished dataset with other settings"
            )
        ids = [args.only]
    done = 0
    for did in ids:
        registry = reg.load()
        e = reg.get(registry, did)
        if e["status"] in FINAL:
            continue
        if n_new_success(registry) >= args.target_successes and not args.only:
            print(f"target of {args.target_successes} new SUCCESS cases reached; stopping")
            break
        if args.max_candidates is not None and done >= args.max_candidates:
            break
        print(f"=== screening {did} ===", flush=True)
        try:
            if not e.get("files"):
                try:
                    dl.download_one(did, max_mb=args.max_mb, allow_large=args.allow_large)
                except (SystemExit, Exception) as ex:  # noqa: BLE001 - data unavailable != verdict
                    registry = reg.load()
                    e = reg.get(registry, did)
                    e["status"], e["status_reason"] = (
                        "NOT_RUN",
                        f"download unavailable/refused: {ex!r}",
                    )
                    reg.save(registry)
                    print(e["status_reason"], flush=True)
                    done += 1
                    continue
            res = sc.screen(did, argv=sys.argv)
            print(json.dumps({k: res[k] for k in ("dataset_id", "status", "reason")}), flush=True)
        except Exception as ex:  # noqa: BLE001
            # A crash is an implementation bug, not a verdict on the dataset: keep it QUEUED,
            # record the error, and stop so the bug can be fixed without touching any setting.
            traceback.print_exc()
            registry = reg.load()
            e = reg.get(registry, did)
            e["last_error"] = repr(ex)
            reg.save(registry)
            write_reports(registry)
            return 1
        done += 1
        write_reports(reg.load())
    write_reports(reg.load())
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--resume", action="store_true", help="skip finished candidates (always on)")
    ap.add_argument("--only", default=None)
    ap.add_argument("--max-candidates", type=int, default=None)
    ap.add_argument("--target-successes", type=int, default=2)
    ap.add_argument("--max-mb", type=int, default=1500)
    ap.add_argument("--allow-large", action="store_true")
    ap.add_argument("--report-only", action="store_true")
    a = ap.parse_args(argv)
    if a.report_only:
        write_reports(reg.init_registry())
        return 0
    return run(a)


if __name__ == "__main__":
    sys.exit(main())
