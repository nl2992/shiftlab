"""Stage 3: staged search over the typed HG x H2c grammar (PROTOCOL A2 budget table, A1.5, A1.6, A3, A5).

Rungs (A2): gen = 1e6 structure-stratified canonical candidates (seed 0, NOT_SAMPLED accounting); rung 0 screening
(16 seeds x 32 cells, T=1000, increments of 2e5, Jaccard stopping rule on the top-10,000 set); rung 1 mechanism development
(10,000 cands, 64 seeds x all 648 dev cells, T=2000); rung 2 stress (500 cands, 128 seeds); rung 3 audit (25-50 cands,
256 seeds, equivalence tests E1-E10). Objective = gain vs the best PRIMARY (anytime-valid) frontier member per cell (A5);
gains against CUSUM/PH are logged (dJ_sec) but never optimised.

Resumable: per-rung, per-candidate-chunk checkpoints in <out>/ckpt; <out>/registry.parquet/ is a directory of
append-only part files (never rewritten). Requires a frozen frontier. Never reads the confirm partition.
Ends with <out>/finalists.json and <out>/selector.json, both frozen (freeze.py).

  PYTHONPATH=src .venv/Scripts/python.exe scripts/hgxh2c/stage3_search.py [--smoke] [--bench]
"""

import argparse
import itertools
import json
import time
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd
import torch

from shiftlab.hgxh2c import freeze, stats
from shiftlab.hgxh2c import grammar as G
from shiftlab.hgxh2c import search as SR
from shiftlab.hgxh2c import tapes as TP

ROOT = Path(__file__).resolve().parents[2]


@dataclass
class Plan:  # PROTOCOL Amendment A2 budget table (ceilings, not targets); smoke shrinks everything
    n0: int = 1_000_000  # generated by structure-stratified sampling (seed 0)
    inc0: int = 200_000  # rung-0 increment for the Jaccard stopping rule
    keep0: int = 10_000  # top set tracked by the stopping rule and promoted to rung 1
    jaccard: float = 0.95  # stop when |top_k(n) & top_k(n - inc)| / |union| >= this (< 5% change)
    seeds0: int = 16
    cells0: int = 32
    T0: int = 1000
    seeds1: int = 64  # rung 1: all 648 dev cells, T=2000, 10,000 candidates
    keep1: int = 500
    T12: int = 2000
    max_cells: int = 0  # 0 = all dev cells at rung 1
    seeds2: int = 128  # rung 2: stress grid, 500 candidates
    keep2: int = 50
    seeds3: int = 256  # rung 3: audit, 25-50 candidates
    final_max: int = 5
    chunk: int = 32768
    small: bool = False
    dev_sel_seeds: int = 32


SMOKE = Plan(
    n0=192,
    inc0=96,
    keep0=24,
    jaccard=0.0,
    seeds0=8,
    cells0=6,
    T0=150,
    seeds1=8,
    keep1=12,
    T12=200,
    max_cells=10,
    seeds2=4,
    keep2=6,
    seeds3=8,
    final_max=3,
    chunk=96,
    small=True,
    dev_sel_seeds=8,
)


def smoke_dev_cells(T):
    mk = lambda f, m, d, r, p: TP.ScenarioCell(f, m, d, r, p, T)
    return [mk("coshift", 0.16, 5, "b20", "good"), mk("null_stationary", 0.0, 5, "b20", "good"), mk("null_boundary", 0.0, 0, "full", "good"),
            mk("cost_only", 0.16, 0, "full", "noisy"), mk("opposed", 0.16, 20, "b05", "biased"), mk("pred_only", 0.16, 5, "b20", "good"),
            mk("lagged", 0.16, 5, "b20", "good"), mk("gradual", 0.16, 0, "full", "good"), mk("intermittent", 0.16, 5, "b05", "good"),
            mk("null_ar", 0.0, 5, "b20", "good")]  # fmt: skip


def make_smoke_frontier(out, freeze_file, device):
    """Small stand-in for stage 2 (J-track baselines on smoke cells) so --smoke is self-contained."""
    from shiftlab.hgxh2c.baselines import REGISTRY
    from shiftlab.hgxh2c.evaluate import run

    cells = smoke_dev_cells(SMOKE.T12) + smoke_dev_cells(SMOKE.T0)
    ids = [m for m, v in REGISTRY.items() if v[1] == "J" and not m.startswith(("cusum", "ph"))]
    df = pd.concat(
        [
            run(ids, [c for c in cells if c.T == T], "dev", 16, device)
            for T in sorted({c.T for c in cells})
        ],
        ignore_index=True,
    )
    s = pd.concat(
        [stats.summarise(df[df.cell_id == c.cell_id], c.T) for c in cells], ignore_index=True
    )
    s.to_parquet(out / "summary.parquet", index=False)
    fr = stats.frontier(s, tracks="J")
    fr["config"] = {"smoke": True}
    (out / "frontier.json").write_text(json.dumps(fr, indent=1))
    freeze.freeze("frontier", out / "frontier.json", freeze_file)


def rp(p):
    p = Path(p)
    return p if p.is_absolute() else ROOT / p


def run_rung(r, src, n_total, cells, n, partition, plan, ck, reg, device, fr, upto=None):
    """Evaluate chunks [0, upto) with per-chunk checkpoints; src(ci) yields the candidates of chunk ci (called in order).
    Returns (df with 'cand' column, behavioural features, baseline features)."""
    ck.mkdir(parents=True, exist_ok=True)
    bf = ck / "baseline.npz"
    if bf.exists():
        z = np.load(bf)
        if (
            str(z["scoring"]) != SR.SCORING
        ):  # never resume from chunks scored under another definition
            raise RuntimeError(
                f"{bf} was written under scoring {z['scoring']}, expected {SR.SCORING}"
            )
        JP, JS, bfeat = z["JP"], (z["JS"] if z["JS"].size else None), z["feats"]
    else:
        b = SR.baseline_table(fr, cells, n, partition, device)
        JP, JS, bfeat = b["JP"], b["JS"], b["feats"]
        np.savez(
            bf,
            JP=JP,
            JS=JS if JS is not None else np.zeros(0),
            feats=bfeat,
            members=np.array(b["members"]),
            scoring=SR.SCORING,
        )
    dfs, feats = [], []
    nch = (n_total + plan.chunk - 1) // plan.chunk
    for ci in range(upto if upto is not None else nch):
        f = ck / f"chunk{ci:05d}.parquet"
        cands = src(ci)
        if not f.exists():
            t0 = time.perf_counter()
            tabs = SR.eval_cands(cands, cells, n, partition, device)
            d = SR.summarise(tabs, JP, cells, JS)
            d.insert(0, "hash", [c.hash for c in cands])
            d["cand"] = [json.dumps(c.to_dict()) for c in cands]
            d["structure"] = [c.structure for c in cands]
            d["n_ops"] = [c.n_ops for c in cands]
            np.save(ck / f"chunk{ci:05d}.npy", tabs["af"].astype(np.float16))
            np.save(
                ck / f"chunk{ci:05d}.J.npy", tabs["J"].astype(np.float32)
            )  # per-cell candidate J: rescoring needs no recompute
            d.to_parquet(f.with_suffix(".tmp"), index=False)
            f.with_suffix(".tmp").replace(f)
            sec = time.perf_counter() - t0
            with open(ck / "timings.jsonl", "a") as fh:
                fh.write(
                    json.dumps(
                        {
                            "chunk": ci,
                            "n": len(cands),
                            "seeds": n,
                            "cells": len(cells),
                            "T": cells[0].T,
                            "sec": sec,
                            "cand_per_s": len(cands) / sec,
                        }
                    )
                    + "\n"
                )
            print(
                f"rung {r} chunk {ci + 1}/{nch}: {len(cands)} cands in {sec:.1f}s ({len(cands) / sec:.1f} cand/s)",
                flush=True,
            )
            ex = [
                f'{{"dJ_sec": {x:.6g}, "frac_worse": {y:.4g}}}'
                for x, y in zip(d.dJ_sec, d.frac_worse)
            ]
            reg.append(
                f"r{r}-c{ci:05d}",
                d.assign(rung=r, status="evaluated", reason=None, novelty=np.nan, extra=ex),
            )
        dfs.append(pd.read_parquet(f))
        feats.append(np.load(ck / f"chunk{ci:05d}.npy").astype(np.float32))
    return pd.concat(dfs, ignore_index=True), np.concatenate(feats), bfeat


def commit(r, df, idx, reg, ck):
    """Write selected.json + registry rows for kept / screened-out candidates."""
    sel = df.iloc[idx]
    (ck / "selected.json").write_text(json.dumps([json.loads(c) for c in sel.cand]))
    reg.append(
        f"r{r}-kept",
        sel.assign(rung=r, status="kept", reason=f"top_{r}", novelty=np.nan, extra=None),
    )
    reg.append(
        f"r{r}-screen",
        df[df.far_lo > SR.ALPHA].assign(
            rung=r, status="rejected", reason="FAR_SCREEN", novelty=np.nan, extra=None
        ),
    )
    return [G.Candidate.from_dict(json.loads(c)) for c in sel.cand]


def load_sel(ck):
    f = ck / "selected.json"
    return [G.Candidate.from_dict(d) for d in json.loads(f.read_text())] if f.exists() else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument(
        "--bench",
        action="store_true",
        help="time candidates at rung-0 fidelity and project the A2 wall time",
    )
    ap.add_argument("--bench-n", type=int, default=3000)
    ap.add_argument("--out", default="outputs/hgxh2c/stage3")
    ap.add_argument("--freeze-file", default=None)
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    ap.add_argument("--n0", type=int, default=0)
    ap.add_argument("--max-cells", type=int, default=-1)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    plan = SMOKE if a.smoke else Plan()
    if a.n0:
        plan.n0 = a.n0
    if a.max_cells >= 0:
        plan.max_cells = a.max_cells
    out = ROOT / (a.out + ("_smoke" if a.smoke and a.out == "outputs/hgxh2c/stage3" else ""))
    out.mkdir(parents=True, exist_ok=True)
    ffile = (
        Path(a.freeze_file)
        if a.freeze_file
        else (out / "FREEZE.json" if a.smoke else freeze.FREEZE)
    )
    dev = a.device
    if a.bench:
        return bench(a, plan, dev, out)
    if a.smoke and "frontier" not in freeze.read_freeze(ffile):
        make_smoke_frontier(out, ffile, dev)
    d = freeze.require_frozen(["frontier"], ffile)
    fr = SR.Frontier(rp(d["frontier"]["path"]))
    reg = SR.Registry(out / "registry.parquet", prefix="a6-")
    ckr = lambda r: out / "ckpt" / f"rung{r}"
    n0 = min(plan.n0, G.space_size()["canonical"])

    # ---- gen + rung 0: structure-stratified sample, increments of inc0, Jaccard stopping rule on the top-keep0 set
    if load_sel(ckr(0)) is None:
        rej = [
            (c, G.canonicalise(c)[1]) for c in G.sample_raw(2000 if not a.smoke else 100, a.seed)
        ]
        reg.append(
            "rej-r0",
            pd.DataFrame(
                [
                    {
                        "rung": 0,
                        "hash": c.hash,
                        "status": "rejected",
                        "reason": w,
                        "cand": json.dumps(c.to_dict()),
                        "structure": c.structure,
                    }
                    for c, w in rej
                    if w
                ]
            ),
        )
        cells = SR.pick_cells(plan.cells0, plan.T0, fr, a.seed, n_null=2 if a.smoke else 6)
        gen, got = G.enumerate(n0, seed=a.seed), {}

        def src(ci):
            while src.next <= ci:
                got[src.next] = list(itertools.islice(gen, plan.chunk))
                src.next += 1
            return got[ci]

        src.next = 0
        nch, per_inc = (n0 + plan.chunk - 1) // plan.chunk, max(1, plan.inc0 // plan.chunk)
        prev, upto = None, 0
        while upto < nch:
            upto = min(nch, upto + per_inc)
            df, feats, bfeat = run_rung(
                0, src, n0, cells, plan.seeds0, "dev", plan, ckr(0), reg, dev, fr, upto
            )
            top = set(df.hash.iloc[SR.select_top(df, plan.keep0)])
            jac = None if prev is None else len(top & prev) / max(1, len(top | prev))
            print(
                f"rung 0: {len(df)} sampled, Jaccard(top-{plan.keep0}) vs previous increment = {jac}",
                flush=True,
            )
            with (ckr(0) / "jaccard.jsonl").open("a") as fh:
                fh.write(json.dumps({"n": len(df), "jaccard": jac}) + "\n")
            if jac is not None and jac >= plan.jaccard:
                break
            prev = top
        idx, nov = SR.select_rung0(df, feats, bfeat, df.n_ops.to_numpy(), min(plan.keep0, len(df)))
        df["novelty"] = nov
        reg.append(
            "r0-novelty",
            df.iloc[idx].assign(rung=0, status="novelty", reason="diversity_term", extra=None),
        )
        sizes = G.space_size()["canonical_by_structure"]
        smp = df.groupby("structure").size()
        reg.append(
            "gen-quota",
            pd.DataFrame(
                [
                    {
                        "rung": 0,
                        "hash": f"structure-{st}",
                        "status": "gen_quota",
                        "reason": f"NOT_SAMPLED:{sizes[st] - int(smp.get(st, 0))}",
                        "structure": st,
                        "extra": json.dumps(
                            {
                                "canonical_size": sizes[st],
                                "sampled": int(smp.get(st, 0)),
                                "seed": a.seed,
                                "planned_n": n0,
                            }
                        ),
                    }
                    for st in range(1, 64)
                ]
            ),
        )
        commit(0, df, idx, reg, ckr(0))

    # ---- rung 1: mechanism development on all dev cells (T=2000), Pareto(Delta_J, power, labels)
    grid = TP.dev_grid(plan.T12)
    cells12 = (
        smoke_dev_cells(plan.T12)
        if a.smoke
        else (
            grid[:: max(1, len(grid) // plan.max_cells)][: plan.max_cells]
            if plan.max_cells
            else grid
        )
    )
    if load_sel(ckr(1)) is None:
        cs = load_sel(ckr(0))[:10_000]
        df, _, _ = run_rung(
            1,
            lambda ci: cs[ci * plan.chunk : (ci + 1) * plan.chunk],
            len(cs),
            cells12,
            plan.seeds1,
            "dev",
            plan,
            ckr(1),
            reg,
            dev,
            fr,
        )
        commit(1, df, SR.select_pareto(df, plan.keep1), reg, ckr(1))
    # ---- rung 2: cross-regime stress (d in {0,5,20,50}, AR nulls, sparse labels)
    if load_sel(ckr(2)) is None:
        cs = load_sel(ckr(1))[:500]
        df, _, _ = run_rung(
            2,
            lambda ci: cs[ci * plan.chunk : (ci + 1) * plan.chunk],
            len(cs),
            SR.stress_cells(plan.T12, plan.small),
            plan.seeds2,
            "stress",
            plan,
            ckr(2),
            reg,
            dev,
            fr,
        )
        commit(2, df, SR.select_top(df, plan.keep2), reg, ckr(2))
    stress = pd.concat(
        [pd.read_parquet(f) for f in sorted(ckr(2).glob("chunk*.parquet"))], ignore_index=True
    )
    # ---- rung 3: audit
    c3 = load_sel(ckr(2))[:50]
    fin = audit(a, plan, c3, fr, reg, dev, out, ffile, stress)
    print("finalists:", [f["hash"] for f in fin["finalists"]], flush=True)


def audit(a, plan, cands, fr, reg, dev, out, ffile, stress):
    if (out / "finalists.json").exists() and "finalists" in freeze.read_freeze(ffile):
        return json.loads((out / "finalists.json").read_text())
    cells = SR.audit_cells(plan.T12, plan.small)
    n = plan.seeds3
    base = SR.baseline_table(fr, cells, n, "audit", dev)
    tabs = SR.eval_cands(cands, cells, n, "audit", dev)
    sc = SR.summarise(tabs, base["JP"], cells, base["JS"])
    suite = SR.equivalence_suite(
        cands, fr, dev, n=8, T=min(500, plan.T12)
    )  # E1-E10 (E11 is the stage-4 size audit)
    eq = {h: v["E2"]["res"] for h, v in suite.items()}
    abl = {}
    for i, c in enumerate(cands):
        for s in range(6):
            if c.slots[s]:
                abl.setdefault(c.without(s).hash, (c.without(s), []))[1].append((i, s))
    ablc = [v[0] for v in abl.values()]
    atabs = SR.eval_cands(ablc, cells, n, "audit", dev) if ablc else None
    ablation = [{} for _ in cands]
    for k, (cd, lst) in enumerate(abl.values()):
        for i, s in lst:
            ablation[i]["_".join(G.SLOTS[s])] = float((atabs["J"][k] - tabs["J"][i]).mean())
    nc = np.zeros(len(cands))
    for which in ("B", "C", "BC"):
        sub = [
            i
            for i, c in enumerate(cands)
            if ("B" if any(c.slots[:3]) else "") + ("C" if any(c.slots[3:]) else "") == which
        ]
        if sub:
            t = SR.eval_cands(
                [cands[i] for i in sub],
                cells,
                n,
                "audit",
                dev,
                transform=lambda tp, w=which: SR.shuffled(tp, w),
            )
            nc[sub] = (t["J"] - tabs["J"][sub]).mean(1)
    stress_dJ = dict(zip(stress.hash, stress.dJ)) if stress is not None else {}
    rows = [
        {
            "hash": c.hash,
            "structure": c.structure,
            "dJ_audit": float(sc.dJ[i]),
            "dJ_sec_audit": float(sc.dJ_sec[i]),
            "dJ_stress": float(stress_dJ.get(c.hash, np.nan)),
            "far_lo": float(sc.far_lo[i]),
            "equivalent": None if eq[c.hash] == "not equivalent" else eq[c.hash],
            "ablation": ablation[i],
            "negative_control": float(nc[i]),
            "power": float(sc.power[i]),
            "labels": float(sc.labels[i]),
        }
        for i, c in enumerate(cands)
    ]
    aud = pd.DataFrame(rows)
    reg.append(
        "r3-audit",
        pd.DataFrame(
            {
                "rung": 3,
                "hash": aud.hash,
                "status": "audited",
                "reason": aud.equivalent,
                "cand": [json.dumps(c.to_dict()) for c in cands],
                "structure": aud.structure,
                "dJ": aud.dJ_audit,
                "far_lo": aud.far_lo,
                "power": aud.power,
                "labels": aud.labels,
                "extra": [
                    json.dumps(
                        {
                            "ablation": r.ablation,
                            "negative_control": r.negative_control,
                            "dJ_stress": r.dJ_stress,
                            "dJ_sec_audit": r.dJ_sec_audit,
                            "suite": suite[r.hash],
                        },
                        default=str,
                    )
                    for r in aud.itertuples()
                ],
            }
        ),
    )
    ok = aud[aud.equivalent.isna() & (aud.far_lo <= SR.ALPHA)].copy()
    ok["score"] = ok[["dJ_audit", "dJ_stress"]].mean(axis=1, skipna=True)
    ok = ok.sort_values("score", ascending=False)
    pick, seen = [], set()
    for r in ok.itertuples():  # distinct structures first, then fill
        if r.structure not in seen and len(pick) < plan.final_max:
            pick.append(r.hash), seen.add(r.structure)
    for r in ok.itertuples():
        if r.hash not in pick and len(pick) < min(plan.final_max, 3):
            pick.append(r.hash)
    byh = {c.hash: c for c in cands}
    fcs = [byh[h] for h in pick]
    reg.append(
        "r3-final",
        pd.DataFrame(
            {
                "rung": 3,
                "hash": pick,
                "status": "finalist",
                "reason": "rung3",
                "cand": [json.dumps(c.to_dict()) for c in fcs],
                "structure": [c.structure for c in fcs],
            }
        ),
    )
    sc_cells = SR.stress_cells(plan.T12, plan.small)
    sp = G.space_size()
    sp["canonical_by_structure"] = None
    out_fin = {
        "finalists": [],
        "N_per_cell_alt": 1000,
        "N_per_cell_null": 1000,
        "power_calc": {},
        "selector": None,
        "space": sp,
        "plan": plan.__dict__,
        "frontier_sha256": freeze.read_freeze(ffile)["frontier"]["sha256"],
        "negative_result": not fcs,
        "comparator_families": {"primary": list(fr.union), "secondary": list(fr.secondary)},
    }
    if fcs:
        st = SR.finalist_tables(fcs, fr, sc_cells, plan.seeds2, "stress", dev)
        dv = SR.finalist_tables(
            fcs,
            fr,
            smoke_dev_cells(plan.T12) if a.smoke else TP.dev_grid(plan.T12),
            plan.dev_sel_seeds,
            "dev",
            dev,
        )
        mem = list(
            st["ref"]
        )  # A6: paired differences against each finalist's binding (hardest) primary member
        diffs = np.stack(
            [
                st["ref"][min(mem, key=lambda m: (st["ref"][m] - st["J"][k]).mean())] - st["J"][k]
                for k in range(len(fcs))
            ]
        )
        pc = {c.hash: SR.power_n(diffs[k], len(fcs)) for k, c in enumerate(fcs)}
        out_fin["power_calc"] = pc
        out_fin["N_per_cell_alt"] = max(v["N"] for v in pc.values())
        out_fin["N_per_cell_null"] = max(1000, int(np.ceil(20000 / 27)))
        sel = SR.fit_selector([c.hash for c in fcs], [st, dv])
        (out / "selector.json").write_text(json.dumps(sel, indent=1))
        out_fin["selector"] = "selector.json"
    for c in fcs:
        r = aud[aud.hash == c.hash].iloc[0]
        out_fin["finalists"].append(
            {
                "hash": c.hash,
                "cand": c.to_dict(),
                "structure": c.structure,
                "audit": r.drop("hash").to_dict(),
                "equivalence": suite[c.hash],
            }
        )
    (out / "finalists.json").write_text(
        json.dumps(
            out_fin,
            indent=1,
            default=lambda o: float(o) if isinstance(o, (np.floating, np.integer)) else str(o),
        )
    )
    if not (out / "selector.json").exists():
        (out / "selector.json").write_text(
            json.dumps({"finalists": [], "table": {}, "cut": [0, 0], "global_best": 0})
        )
    freeze.freeze("finalists", out / "finalists.json", ffile)
    freeze.freeze("selector", out / "selector.json", ffile)
    return out_fin


def bench(a, plan, dev, out):
    """Rung-0 throughput (16 seeds x 32 cells, T=1000) on the stratified sample, and the A2 wall-time projection."""
    P = Plan()
    cells = TP.dev_grid(P.T0)[:: 648 // 32][:32]
    cands = list(G.enumerate(a.bench_n))
    SR.eval_cands(cands[:64], cells, P.seeds0, "dev", dev)  # warm-up
    t0 = time.perf_counter()
    SR.eval_cands(cands, cells, P.seeds0, "dev", dev)
    sec = time.perf_counter() - t0
    unit = sec / (len(cands) * P.seeds0 * len(cells) * P.T0)
    n_stress = len(SR.stress_cells(P.T12))
