# R3: Markov SUI with alternative numerators (denominator untouched)
# ------------------------------------------------------------------------------------------------
class MarkovSUIPlus(fam_a.MarkovSUI):
    """fam_a.MarkovSUI with (a) an optional predictable plug-in numerator component and
    (b) an optional tilted prior over the alternative p grid.

    Numerator for start s: ``(1 - beta) * Q_grid(s:k) + beta * Q_plug(s:k)``, where ``Q_plug`` is
    the likelihood of the predictable plug-in predictor
    ``P(hit_k = 1) = a_k prev + (1 - a_k) phat_{k-1}``, ``a_k = rhohat_{k-1}^{gap_k}``,
    ``phat_{k-1} = clip((n1 + 1) / (n + 2), .5, .95)`` and ``rhohat`` the shrunk gap-indexed MLE
    (fam_a.rho_mle, sig = 2) of the previous outcomes, all computed BEFORE outcome k is seen. A
    mixture of predictable predictive distributions is a predictive distribution, so each start's
    ``Q / U`` is still dominated by a test martingale under every null member.
    """

    def __init__(self, beta=0.0, p_tilt=0.0, rho_every=5, **kw):
        super().__init__(**kw)
        self.beta, self.rho_every = float(beta), int(rho_every)
        if p_tilt > 0:  # prior on ALT_P proportional to (p' - 1/2)^(-p_tilt), renormalised per rho
            nr = len(fam_a.ALT_RHO)  # alogpi is laid out (rho, p) with p fastest (meshgrid)
            w = (fam_a.ALT_P - 0.5) ** (-p_tilt)
            w = w / w.sum()
            rprior = np.exp(self.alogpi).reshape(nr, -1).sum(axis=1)
            self.alogpi = np.log((rprior[:, None] * w[None, :]).ravel())
        self.pcum = 0.0
        self._z: list[int] = []
        self._t: list[int] = []
        self._tnow = 0
        self._rho = 0.0

    def _plug_factor(self, hit, gap, prev):
        n = len(self._z)
        ph = min(max((sum(self._z) + 1.0) / (n + 2.0), 0.5), 0.95)
        if prev is None or self._rho <= 0:
            m = ph
        else:
            a = self._rho ** max(gap, 1)
            m = a * prev + (1.0 - a) * ph
        return math.log(m if hit else 1.0 - m)

    def update(self, hit: int, gap: int, prev) -> float:
        if self.beta <= 0:
            return super().update(hit, gap, prev)
        # snapshot the plug-in cumulative alongside the parent's snapshots
        self.k += 1
        new_start = (self.k - 1) % self.stride == 0 and (self.started or self.k == 1)
        if new_start:
            self.starts.append((self.cum.copy(), self.acum.copy(), self.pcum))
        self.cum = np.maximum(self.cum + self._null_factor(hit, gap, prev), fam_a.LOG0)
        self.acum = np.maximum(self.acum + self._alt_factor(hit, gap, prev), fam_a.LOG0)
        self.pcum = max(self.pcum + self._plug_factor(hit, gap, prev), fam_a.LOG0)
        # predictable state update (used only for the NEXT outcome)
        self._tnow += max(gap, 1) if self._z else 0
        self._z.append(int(hit))
        self._t.append(self._tnow)
        if len(self._z) >= 9 and len(self._z) % self.rho_every == 0:
            r = fam_a.rho_mle(np.array(self._z[-150:]), np.array(self._t[-150:]), sig=2.0)
            self._rho = 0.0 if r is None else r
        lb = math.log(self.beta)
        l1b = math.log(1.0 - self.beta)
        terms = []
        for m, (c0, a0, p0) in enumerate(self.starts, start=1):
            if not self.started:
                w = 1.0
            elif m == 1:
                w = self.w_first
            else:
                w = 2.0 * (1.0 - self.w_first) / (m * (m + 1))
            num = fam_a._lse(
                np.array([l1b + fam_a._lse(self.alogpi + self.acum - a0), lb + self.pcum - p0])
            )
            den = float(np.max(self.cum - c0))
            terms.append(math.log(w) + num - den)
        self.log_value = fam_a._lse(np.array(terms))
        self.value = float(math.exp(min(self.log_value, 700.0)))
        return self.value


def markov_cert(**kw):
    """Factory: side -> fam_d._A1Cert over MarkovSUIPlus(kw), defaults = fam_a._B (A1b/A5b)."""
    kw = {**fam_a._B, **kw}
    return lambda side: fam_d._A1Cert(side, MarkovSUIPlus, **kw)


class _QCCert:
    """``cmq``: CondMeanEP on query-conditional hits (Y = hit in {0, 1})."""

    def __init__(self, side, lams=LAMS):
        self.side, self.m = side, CondMeanEP(lams)

    def update(self, z, event_t, last=None):
        return self.m.update(float(z if self.side > 0 else 1 - z))


