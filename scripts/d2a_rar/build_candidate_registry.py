"""Build the candidate registry, the Stage-B batch, the dev-suite checksum and CANDIDATE_REGISTRY.md.

Deterministic: identical bytes on rerun (gzip mtime=0, sorted keys, no timestamps). Run:
    PYTHONPATH=src python scripts/d2a_rar/build_candidate_registry.py [--check]
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from shiftlab.autoresearch import grammar as g
from shiftlab.autoresearch.dev_suite import DEV_SUITE, missing_references, suite_sha256

REG = ROOT / "docs" / "d2a_rar" / "registry"
DOC = ROOT / "docs" / "d2a_rar" / "CANDIDATE_REGISTRY.md"
GZ_THRESHOLD = 5_000_000


def jsonl_bytes(rows: list[dict]) -> bytes:
    return b"".join(
        (json.dumps(r, sort_keys=True, separators=(",", ":"), ensure_ascii=False) + "\n").encode(
            "utf-8"
        )
        for r in rows
    )


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def counts(rows: list[dict], key: str) -> dict:
    return dict(sorted(Counter(r[key] for r in rows).items()))


def build() -> dict:
    reg = g.build_registry()
    ids, stats = reg["identities"], reg["stats"]
    batch = g.select_batch(ids)
    for r in ids:
        r["in_stage_b_batch_001"] = False
    bid = {c["candidate_id"] for c in batch}
    for r in ids:
        r["in_stage_b_batch_001"] = r["candidate_id"] in bid
    batch = [r for r in ids if r["candidate_id"] in bid]
    batch.sort(key=lambda c: (-c["priority_score"], c["candidate_id"]))
    bad = [(r["candidate_id"], e) for r in ids if (e := g.validate_identity(r))]
    if bad:
        raise SystemExit(f"grammar violations: {bad[:5]}")
    return {"ids": ids, "stats": stats, "batch": batch}


def render_md(b: dict, shas: dict) -> str:
    ids, stats, batch = b["ids"], b["stats"], b["batch"]
    per_fam = defaultdict(lambda: Counter())
    for r in ids:
        f = per_fam[r["family"]]
        f["n"] += 1
        f[r["research_question"]] += 1
        f["blocked_by"] += bool(r["blocked_by"])
        f["batch"] += r["in_stage_b_batch_001"]
    fam_meta = {f.key: f for f in g.families()}
    L = []
    a = L.append
    a("# Candidate registry (WP5) - Drift2Act / RAR programme\n")
    a(
        "Generated by `scripts/d2a_rar/build_candidate_registry.py` (grammar "
        f"`{g.GRAMMAR_VERSION}`); do not edit by hand. **These are candidate identities (structured hypotheses), "
        "not experiments and not results.** No candidate is declared novel: `prior_art_status` is inherited from "
        "`registry/prior_art.yaml` (a failed search is not proof of novelty); families the WP4 ledger did not cover "
        "are UNVERIFIED.\n"
    )
    a("## 1. Grammar summary\n")
    a(
        "An identity = `host x research_question x mechanism family x variant x target_null x discrete knobs`. "
        "Source of truth: `src/shiftlab/autoresearch/grammar.py` (types, hooks, rules, dedup, scoring) and "
        "`families.py` (24 Phase-5 families, one table row per variant).\n"
    )
    a(
        "- Hosts: `drift2act`, `rar`, `cost_aware_binary` (RAR harness mode), `challenger`, `contract_native`."
    )
    a(
        "- Questions: Q1 gap-aware evidence, Q2 decision-valued labels / decisions, Q3 integration (J00/J10/J01/J11)."
    )
    a(
        "- Nulls: `cond`, `marg`, `absolute_risk`, `economic`, `none` (registry/null_assumptions.yaml classes)."
    )
    a("- Knobs: small discrete sets; the first value is the default. `parent_id` = the default-config sibling "
      "(or `BASE-<host>` for the default itself); Q3 identities have `parent_ids` = [Q1 constituent, Q2 constituent].\n")  # fmt: skip
    a("Identity key: `candidate_id = CAND-` + 16 hex of `behavioural_signature` = sha256(`mechanism_signature`, "
      "config with inert knobs masked); `mechanism_signature` = sha256(canonical mechanism, host, question, null, "
      "hook, new-hypothesis text).\n")  # fmt: skip
    a("### Compatibility rules (enforced by `validate_identity`)\n")
    for t in (
        "Gate-2 mechanisms (`rar.gate2`) only on `rar`; Gate-3 only on `rar` or `cost_aware_binary`.",
        (
            "A `request_size` mechanism only through the Drift2Act hook `d2a.request_size`; on Drift2Act every Q2 "
            "acquisition family must use it (it decides HOW MANY labels, never which index), so per-item propensity "
            "knobs are inert there (`propensity_score` masked)."
        ),
        "A mechanism needing gap-aware evidence must declare `target_null` in {cond, marg}.",
        (
            "Each variant lists the hook per host it supports; the null must be allowed on the host "
            "(`HOST_ALLOWED_NULLS`) and declared by the variant; `scoring_null == target_null` always "
            "(a cond method is never scored on the marginal null)."
        ),
        (
            "HIGH_OVERLAP / KNOWN prior-art status => `role = baseline_or_ablation_only` (or `narrow_residue_test` for the "
            "F4 VOQ-vs-certificate-state variants) and `novelty_bearing = false`."
        ),
        (
            "Q3 identities carry `blocked_until = 'Q1 and Q2 winners'`. Q3 is generated only on drift2act and "
            "contract_native (RAR has no Q1 evidence hook)."
        ),
        (
            "A variant matching a `do_not_repeat_without` construction gets `blocked_by` (ledger id + requirement) unless a "
            "`new_mechanistic_hypothesis` is declared."
        ),
        (
            "Mandatory comparators: Q1 {Markov-LR, Sethi plug-in on thinned chain, fixed spacing, restart-without-gaps, "
            "conditional-null certifier, Page-CUSUM}; Q2 {uniform, pending cap, fixed schedule, front-loaded, Drift2Act "
            "native audit, ASI-inspired, Gong-Zhang paid-obs, PAVE}; RAR-gate candidates also unmodified RAR AND "
            "Cost-Aware Binary; Q3 {J00, J10, J01, Gong-Zhang adapted}; plus the WP4 comparators of the mapped family."
        ),
    ):
        a(f"- {t}")
    a("\n### Hook registry\n")
    a("| hook | host | status | note |\n|---|---|---|---|")
    for k, h in g.HOOKS.items():
        a(f"| `{k}` | {h['host']} | {h['status']} | {h['note']} |")
    a("\n## 2. Counts\n")
    a(f"- Raw identities before dedup: **{stats['raw_before_dedup']}** (Q1/Q2 family identities "
      f"{stats['raw_q12_families']}, Q3 factorial {stats['q3_factorial_generated']}).")  # fmt: skip
    a(f"- After dedup: **{stats['after_dedup']}** (hard cap {g.MAX_IDENTITIES:,}); duplicates collapsed: "
      f"{stats['duplicates_collapsed']} (`alias` = other spelling of the same canonical mechanism: "
      f"{stats['dedup_reasons'].get('alias', 0)}; `inert_knob` = configs differing only in knobs inert for that "
      f"host/null/config: {stats['dedup_reasons'].get('inert_knob', 0)}).")  # fmt: skip
    a(f"- Blocked by a ledger `do_not_repeat_without`: {sum(bool(r['blocked_by']) for r in ids)}; "
      f"blocked until Q1 and Q2 winners (Q3): {sum(bool(r['blocked_until']) for r in ids)}.")  # fmt: skip
    for title, key in (
        ("research question", "research_question"),
        ("host", "host"),
        ("target null", "target_null"),
        ("prior-art status", "prior_art_status"),
        ("role", "role"),
    ):
        a(f"- By {title}: " + ", ".join(f"{k} {v}" for k, v in counts(ids, key).items()))
    a("\n### Per family (after dedup)\n")
    a("| family | prior-art family | questions | identities | Q1 | Q2 | Q3 | blocked_by | in batch |\n|---|---|---|---|---|---|---|---|---|")  # fmt: skip
    for k in sorted(per_fam):
        f, m = per_fam[k], fam_meta.get(k)
        a(f"| `{k}` | {m.prior_family if m and m.prior_family else ('F10' if k == 'q3_factorial_stack' else 'unmapped')} | {','.join(m.questions) if m else 'Q3'} "
          f"| {f['n']} | {f['Q1']} | {f['Q2']} | {f['Q3']} | {f['blocked_by']} | {f['batch']} |")  # fmt: skip
    a("\n## 3. Prioritisation (transparent, deterministic)\n")
    a("`score = " + " + ".join(f"{w:.2f}*{k}" for k, w in g.SCORE_WEIGHTS.items()) + f" - {g.CONFIG_SPRAWL_PENALTY} "
      "(non-default knob combination)`. Components in [0,1]:\n")  # fmt: skip
    a(f"- `prior_art`: {g.PRIOR_ART_SCORE}; narrow-residue variants (F4 VOQ vs certificate state, release survival, "
      f"propensity-by-certificate-gap) {g.RESIDUE_PRIOR_ART_SCORE}. PLAUSIBLY_DISTINCT families (F5, F6 Gate-2 / "
      "recovery-gain, F7, F9) therefore rank first.")  # fmt: skip
    a("- `failure_link`: 1.0 if the family links a ledger row whose problem survives the null correction "
      f"(`SURVIVING_FAILURES` = {sorted(g.SURVIVING_FAILURES)}, FAILURE_ATLAS_CORRECTED section 4), 0.5 if it links "
      "only closed/other rows, 0 if none.")  # fmt: skip
    a(f"- `host_strength`: {g.HOST_STRENGTH} (Drift2Act and RAR are the primary hosts).")
    a(
        "- `simplicity`: (6 - complexity level)/5; level = variant complexity + 1 when the hook is NOT_EXPOSED."
    )
    a(f"- `null_eligibility`: {g.NULL_ELIGIBILITY}.")
    a("- Blocked and Q3 identities are never selected. Weights are judgement calls, documented here, not tuned on any "
      "result.\n")  # fmt: skip
    a("## 4. Stage-B batch 001 (200 identities)\n")
    a(f"Selection: top score subject to caps {g.BATCH_CAPS} (per family, per variant, per variant-host-null, per host, "
      "ablation-only share, Q1 min/max); phase A guarantees every unblocked family at least `min_per_family`. "
      "Q3 identities are generated but not selected (blocked_until Q1 and Q2 winners). Negative/neighbouring "
      "controls are cells of the frozen dev suite (`docs/d2a_rar/registry/DEV_SUITE.json`), not candidates.\n")  # fmt: skip
    a(f"Composition: Q {counts(batch, 'research_question')}; host {counts(batch, 'host')}; "
      f"status {counts(batch, 'prior_art_status')}; role {counts(batch, 'role')}; null {counts(batch, 'target_null')}.\n")  # fmt: skip
    a("| family | n | Q1 | Q2 | hosts | variants (n) | statuses |\n|---|---|---|---|---|---|---|")
    bf = defaultdict(list)
    for r in batch:
        bf[r["family"]].append(r)
    for k in sorted(bf):
        rs = bf[k]
        vv = Counter(r["variant"] for r in rs)
        a(f"| `{k}` | {len(rs)} | {sum(r['research_question'] == 'Q1' for r in rs)} | "
          f"{sum(r['research_question'] == 'Q2' for r in rs)} | {', '.join(sorted({r['host'] for r in rs}))} | "
          f"{', '.join(f'{v} ({n})' for v, n in sorted(vv.items()))} | "
          f"{', '.join(sorted({r['prior_art_status'] for r in rs}))} |")  # fmt: skip
    a("\n## 5. Blocked by the failure ledger\n")
    a("| variant | ledger | requirement to unblock |\n|---|---|---|")
    seen = set()
    for r in ids:
        for bb in r["blocked_by"]:
            key = (r["family"], r["variant"], bb["ledger_id"])
            if key not in seen:
                seen.add(key)
                a(
                    f"| `{r['family']}.{r['variant']}` | {bb['ledger_id']} | {bb['requirement'][:160]} |"
                )
    a("\n## 6. Frozen dev suite\n")
    a(f"Defined in `src/shiftlab/autoresearch/dev_suite.py` (sha256 `{suite_sha256()}`), written to "
      "`registry/DEV_SUITE.json`. Missing references: "
      f"{missing_references()}. TODOs for the coordinator (missing stream families):")  # fmt: skip
    for t in DEV_SUITE["TODO_for_coordinator"]:
        a(f"- {t}")
    a("\n## 7. Artefacts and checksums\n")
    for k, v in shas.items():
        a(f"- `{k}`: `{v}`")
    a("\n## 8. Limits\n")
    a(
        "- Identity text (hypotheses, win/failure regions) is hand-written per variant; predictions are hypotheses."
    )
    a("- `closest_prior_art` ids are family-level from `registry/prior_art.yaml`; variant-level novelty has NOT been "
      "searched. Unmapped families are UNVERIFIED.")  # fmt: skip
    a("- Behavioural dedup only collapses provable equivalences (alias spellings, inert knobs); near-duplicates "
      "remain separate identities.")  # fmt: skip
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check", action="store_true", help="build in memory and compare with files on disk"
    )
    args = ap.parse_args()
    b = build()
    full = jsonl_bytes(b["ids"])
    batch_b = jsonl_bytes(b["batch"])
    suite = (json.dumps(DEV_SUITE, sort_keys=True, indent=1, ensure_ascii=False) + "\n").encode(
        "utf-8"
    )
    gz = len(full) > GZ_THRESHOLD
    reg_name = "CANDIDATE_REGISTRY.jsonl.gz" if gz else "CANDIDATE_REGISTRY.jsonl"
    reg_bytes = gzip.compress(full, 9, mtime=0) if gz else full
    shas = {
        "CANDIDATE_REGISTRY.jsonl (uncompressed)": sha(full),
        reg_name: sha(reg_bytes),
        "stage_b_batch_001.jsonl": sha(batch_b),
        "DEV_SUITE.json": sha(suite),
    }
    counts_doc = {
        "grammar_version": g.GRAMMAR_VERSION,
        "stats": b["stats"],
        "identities": len(b["ids"]),
        "batch": len(b["batch"]),
        "by_question": counts(b["ids"], "research_question"),
        "by_host": counts(b["ids"], "host"),
        "by_null": counts(b["ids"], "target_null"),
        "by_family": counts(b["ids"], "family"),
        "by_prior_art_status": counts(b["ids"], "prior_art_status"),
        "batch_by_family": counts(b["batch"], "family"),
        "sha256": shas,
        "uncompressed_bytes": len(full),
    }
    sums = (json.dumps(counts_doc, sort_keys=True, indent=1) + "\n").encode("utf-8")
    md = render_md(b, shas).encode("utf-8")
    outputs = {
        REG / reg_name: reg_bytes,
        REG / "stage_b_batch_001.jsonl": batch_b,
        REG / "DEV_SUITE.json": suite,
        REG / "CANDIDATE_REGISTRY.sha256.json": sums,
        DOC: md,
    }
    if args.check:
        bad = [str(p) for p, data in outputs.items() if not p.exists() or p.read_bytes() != data]
        print("MISMATCH: " + ", ".join(bad) if bad else "OK: files match a fresh build")
        raise SystemExit(1 if bad else 0)
    for p, data in outputs.items():
        p.write_bytes(data)
    stale = REG / ("CANDIDATE_REGISTRY.jsonl" if gz else "CANDIDATE_REGISTRY.jsonl.gz")
    if stale.exists():
        stale.unlink()
    led = REG / "EXPERIMENT_LEDGER.jsonl"
    if not led.exists():
        led.write_bytes(b"")
    for k, v in shas.items():
        print(f"{v}  {k}")
    print(f"identities={len(b['ids'])} batch={len(b['batch'])} stats={b['stats']}")


if __name__ == "__main__":
    main()
