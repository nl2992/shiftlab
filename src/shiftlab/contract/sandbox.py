"""Isolated execution of an external adapter (P4 section 1, Codex review 1).

The AST import check in ``isolation.py`` is only a lint: standard-library modules such as
``pathlib``, ``sys`` or ``inspect`` can still reach repository files. This module runs the
adapter in a separate interpreter instead.

Packet: a temporary directory holding only a standalone copy of ``interface.py``, the adapter
file, the P4 and contract-README documents and a small runner. The adapter runs with
``python -I`` (no user site, no PYTHONPATH, no script directory on the path), ``cwd`` set to the
packet, a stripped environment, and ``shiftlab`` removed from ``sys.path`` and blocked by a
meta-path finder. The harness stays in the parent; events and feedback cross as JSON lines.

Before the adapter is loaded the runner installs a ``sys.addaudithook`` guard (hooks cannot be
removed from Python code). It denies: opening any file outside the packet except read-only access
under the Python prefixes (stdlib and site-packages); ``os.listdir``/``os.scandir``/``glob.glob``
outside the packet and those prefixes; subprocess, ``os.system``, ``os.exec*``, ``os.spawn*``,
``os.posix_spawn``, fork; ``socket.*``; ``ctypes.*``; and importing ctypes/_ctypes/cffi.

The hook is generated by ``guard_source``: the allowed roots are embedded as string/tuple
literals in the code object's constants. It has no closure, no defaults and no global lookup for
the allowlist, runs on a private copy of ``builtins``, and does path checks with pure string
operations, so rebinding ``os``/``builtins`` functions from the adapter cannot change what it
allows. It also denies ``gc.get_objects/get_referrers/get_referents``, ``sys._getframe`` and
``sys._current_frames``, ``sys.settrace/setprofile``, ``builtins.input``, ``os.chdir``,
``os.symlink``/``link``, assignment to ``__code__``/``__closure__``/``__globals__``/
``__defaults__``/``__kwdefaults__``/``__builtins__`` and setting attributes of code, cell or
frame objects, ``function.*``/``code.*``/``cell.*`` events, extension modules loaded from outside
the allowed roots, and importing gc, inspect, ctypes, _ctypes or cffi.

Threat model, stated plainly: a non-adversarial implementer, adapter source that the lead reviews
and hashes before the run (the AST lint in ``isolation.py`` is part of that review), plus this
in-process guard. It is not an OS sandbox. CPython does not audit every mutation (module
attribute writes, cell contents and ``dict`` item assignment are not audited), so a determined
adapter could still tamper with in-process state or a native extension could escape; those are
out of scope. Full isolation additionally requires the implementer session to receive only the
packet, a procedural requirement recorded in the P4 protocol.

The adapter file must define ``build_monitor()`` returning a ``Monitor`` and import the contract
as ``from interface import ...``.
"""

