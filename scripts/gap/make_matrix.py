def sha(path):
    p = path.split(";")[0].split()[0].replace("`", "")
    try:
        return (
            subprocess.run(
                ["git", "log", "-1", "--format=%h", "--", p],
                capture_output=True,
                text=True,
                check=True,
            ).stdout.strip()
            or "uncommitted"
        )
    except Exception:  # noqa: BLE001
        return "n/a"


