def f(x, nd=3):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "n/a"
    return f"{x:.{nd}f}" if abs(x) >= 0.01 or x == 0 else f"{x:.2e}"


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def matrix_doc() -> str:
    pd_ = pd.read_csv(OUT / "matrix_per_dataset.csv")
    po = pd.read_csv(OUT / "matrix_pooled.csv")
    gq = pd.read_csv(OUT / "matrix_geq_counts.csv")
    cc = (OUT / "matrix_crosscheck.json").read_text()
    s = ["# Comparison matrices (nine datasets, arms B and R)\n"]
    s.append(
        "Generated by `scripts/paper1_eqsdp/make_docs.py` from `matrix.py` output. "
        "Delta = J(arm) - J(comparator), seed-mean net cost per episode (T=2000, cs=5, cq=.05, "
        "B=200); negative = arm cheaper. U = one-sided 95% episode-bootstrap upper bound of the "
        "mean paired difference (2,000 resamples, `np.random.default_rng(0)` per cell). "
        "superior: U<0. non-inferior (NI): U < 1% of the comparator's mean J. Certified methods "
        "are **NOT COMPARABLE** (different guarantee class, `02_BASELINE_FIDELITY.md`); only their "
        "cost Delta is shown and they are excluded from every count. `own` = other EQSDp "
        "parameterisations and `reference` = CONTROL_never_switch: shown for completeness, not "
        "counted as comparators.\n"
    )
    s.append("## Cross-check against `all_tier_per_dataset.csv` (tiers S1, S2)\n")
    s.append(f"```json\n{cc}\n```\n")
    s.append("## '>= every uncertified comparator' (non-inferior to all 25 on a dataset)\n")
    t = gq.assign(
        cell=lambda x: x.apply(
            lambda r: f"{'YES' if r.geq_all else 'no'} (NI {r.n_noninf}/25, sup {r.n_sup}/25)",
            axis=1,
        )
    ).pivot(index="dataset", columns="arm", values="cell")
    t = t.reset_index().rename(columns={"B": "arm B", "R": "arm R"})
    s.append(md(t))
    tot = gq.groupby("arm").geq_all.sum()
    s.append(
        f"\n**Datasets with arm >= every uncertified comparator: B {tot['B']}/9, R {tot['R']}/9.**\n"
    )
    for arm, an in data.ARMS.items():
        s.append(f"## Arm {arm} = `{an}`: pooled (equal-dataset) matrix\n")
        s.append(
            "K=9 datasets. mean Delta and mean Delta% are equal-dataset means; t-CI is the "
            "dataset-level t 95% interval of Delta; neg = datasets with Delta<0; p = two-sided "
            "one-sample t-test on dataset Deltas; sup/NI = datasets superior / non-inferior; "
            "pooled NI = upper t bound < 1% of mean comparator J.\n"
        )
        q = po[po.arm == arm].copy()
        q["order"] = q["class"].map(
            {"adapter": 0, "control": 1, "own": 2, "reference": 3, "certified": 4}
        )
        q = q.sort_values(["order", "J_comp"])
        rows = []
        for _, r in q.iterrows():
            nc = r["class"] == "certified"
            rows.append(
                {
                    "comparator": r["comp"],
                    "class": r["class"].replace("certified", "NOT COMPARABLE (certified)"),
                    "mean J": f(r.J_comp, 1),
                    "mean Delta": f(r.mean_delta, 2),
                    "Delta%": f(r.mean_pct, 2),
                    "t 95% CI": "n/a" if nc else f"[{r.t_lo:.2f}, {r.t_hi:.2f}]",
                    "neg": f"{int(r.n_neg)}/9",
                    "p": "n/a" if nc else f(r.t_p, 4),
                    "sup": "n/a" if nc else f"{int(r.n_superior)}/9",
                    "NI": "n/a" if nc else f"{int(r.n_noninf)}/9",
                    "pooled NI": "n/a" if nc else ("yes" if r.pooled_noninf else "no"),
                }
            )
        s.append(md(pd.DataFrame(rows)) + "\n")
        s.append(
            f"### Arm {arm}: per-dataset cells, `Delta (U)` and S = superior, N = non-inferior only\n"
        )
        r = pd_[pd_.arm == arm].copy()
        r["cell"] = r.apply(
            lambda x: (
                f"{x.delta:.2f} ({x.U:.2f})" + (" S" if x.superior else (" N" if x.noninf else ""))
            ),
            axis=1,
        )
        w = r.pivot(index="comp", columns="dataset", values="cell")[data.DATASETS]
        w.columns = [SHORT[c] for c in w.columns]
        cls = r.drop_duplicates("comp").set_index("comp")["class"]
        w.insert(0, "class", cls)
        w = w.reset_index().rename(columns={"comp": "comparator"})
        w["class"] = w["class"].replace({"certified": "NOT COMPARABLE"})
        for c in w.columns[2:]:  # certified: cost Delta only (no U, no flags)
            w[c] = np.where(
                w["class"] == "NOT COMPARABLE", w[c].str.replace(r" \(.*$", "", regex=True), w[c]
            )
        w["o"] = w["class"].map(
            {"adapter": 0, "control": 1, "own": 2, "reference": 3, "NOT COMPARABLE": 4}
        )
        w = w.sort_values(["o", "comparator"]).drop(columns="o")
        s.append(md(w) + "\n")
    s.append(
        "Full numeric cells (n, J_comp, delta, pct, U, flags): `docs/paper1_eqsdp/tables/matrix_per_dataset.csv`; pooled: `matrix_pooled.csv`.\n"
    )
    return "\n".join(s)


def strong_set(po: pd.DataFrame) -> list[str]:
    u = po[(po.arm == "B") & po["class"].isin(["adapter", "control"])].sort_values("J_comp")
    top = u.comp.head(5).tolist()
    for extra in ["qiu_delayed_movement", "gong_zhang_paid_obs", data.NEVER]:
        if extra not in top:
            top.append(extra)
    return top


def measure_doc() -> str:
    v = pd.read_csv(OUT / "measure_values.csv")
    dif = pd.read_csv(OUT / "measure_diffs.csv")
    po = pd.read_csv(OUT / "matrix_pooled.csv")
    strong = strong_set(po)
    rows_pol = [data.ARMS["B"], data.ARMS["R"]] + strong
    label = {data.ARMS["B"]: "ARM B", data.ARMS["R"]: "ARM R"}
    s = ["# Measure results (nine datasets)\n"]
    summ = DOCS / "03_summary_text.md"
    if summ.exists():
        s.append(summ.read_text(encoding="utf-8") + "\n")
    s.append(
        "Generated by `make_docs.py` from `measures.py` output. Values are equal-dataset means "
        "(POOLED) of dataset-level measures; brackets are stratified episode-bootstrap 95% "
        "percentile intervals (2,000 resamples; episodes resampled within dataset). Definitions: "
        "`01_MEASURES.md`. 'Strong set' = the 5 uncertified comparators with the lowest pooled "
        "mean J (from `matrix_pooled.csv`) plus qiu_delayed_movement, gong_zhang_paid_obs and the "
        "frozen incumbent CONTROL_never_switch. **dc_311 has no challenger-not-better episode "
        "(all 100 have gain>0), so every measure restricted to N or S (harm_N, false_promo_*, "
        "wrong_exposure_S, terminal_correct_S) is pooled over the other 8 datasets.** "
        "ttc_given_promoted is n/a in a dataset where a policy never promotes in a C episode "
        "and is pooled over the datasets where it is defined.\n"
    )
    rec = data.load_records()
    g = rec.groupby(["stream", "ep"]).mean_gain.first()
    cnt = (
        pd.DataFrame(
            {
                "C (gain>0)": g.groupby("stream").apply(lambda z: int((z > 0).sum())),
                "S (gain<0)": g.groupby("stream").apply(lambda z: int((z < 0).sum())),
                "tie (gain=0)": g.groupby("stream").apply(lambda z: int((z == 0).sum())),
            }
        )
        .loc[data.DATASETS]
        .reset_index()
        .rename(columns={"stream": "dataset"})
    )
    s.append("## Episode classes per dataset (evaluator-side, from mean_gain)\n")
    s.append(md(cnt) + "\n")
    pv = v[v.dataset == "POOLED"].set_index(["measure", "policy"])
    s.append("## Pooled values: arms B, R and the strong set\n")
    for fam, ms in FAMILIES.items():
        s.append(f"### {fam}\n")
        tab = []
        for p in rows_pol:
            r = {"policy": label.get(p, p)}
            if p not in label:
                r["policy"] = p
            for m in ms:
                x = pv.loc[(m, p)]
                r[m] = "n/a" if np.isnan(x.value) else f"{x.value:.3f} [{x.lo:.3f}, {x.hi:.3f}]"
            tab.append(r)
        s.append(md(pd.DataFrame(tab)) + "\n")
    s.append("## Pooled differences, arm minus comparator, strong set\n")
    s.append(
        "Cell: diff [bootstrap 95% CI]; the mark `+` means the arm is better and the interval "
        "excludes 0, `-` the arm is worse and the interval excludes 0, `0` the interval includes 0 "
        "(direction per measure: higher is better for capture, promoted_C, label_eff_*, "
        "terminal_*; lower is better otherwise, including switches, which is churn).\n"
    )
    pd_ = dif[dif.dataset == "POOLED"]

    def mark(m, r):
        if np.isnan(r["diff"]):
            return "n/a"
        good = (r["diff"] > 0) if m in HIGHER else (r["diff"] < 0)
        sig = (r.lo > 0) or (r.hi < 0)
        tag = "0" if not sig else ("+" if good else "-")
        return f"{r['diff']:.3f} [{r.lo:.3f}, {r.hi:.3f}] {tag}"

    for arm in ("B", "R"):
        s.append(f"### Arm {arm} minus comparator\n")
        tab = []
        for c in strong:
            r = {"comparator": c}
            for m in KEYDIFF:
                x = pd_[(pd_.arm == arm) & (pd_.comp == c) & (pd_.measure == m)]
                r[m] = mark(m, x.iloc[0]) if len(x) else "n/a"
            tab.append(r)
        s.append(md(pd.DataFrame(tab)) + "\n")
    s.append("## Verdict counts over the 25 uncertified comparators (pooled bootstrap CI)\n")
    s.append(
        "Number of comparators on which the arm is better (CI excludes 0) / inconclusive / worse (CI excludes 0).\n"
    )
    unc = set(data.UNCERTIFIED)
    tab = []
    for m in MEASURES:
        r = {"measure": m, "better when": "higher" if m in HIGHER else "lower"}
        for arm in ("B", "R"):
            x = pd_[(pd_.arm == arm) & (pd_.measure == m) & pd_.comp.isin(unc)].dropna(
                subset=["diff"]
            )
            good = (x["diff"] > 0) if m in HIGHER else (x["diff"] < 0)
            sig = (x.lo > 0) | (x.hi < 0)
            r[f"{arm}: better/incl/worse"] = (
                f"{int((good & sig).sum())} / {int((~sig).sum())} / {int((~good & sig).sum())}  (n={len(x)})"
            )
        tab.append(r)
    s.append(md(pd.DataFrame(tab)) + "\n")
    s.append("## Per-dataset values, arms B and R and never_switch\n")
    for m in [
        "harm_all",
        "capture",
        "wrong_exposure",
        "ttc_rmst",
        "promoted_C",
        "false_promo_N",
        "terminal_correct",
        "switches",
        "label_eff_net",
    ]:
        s.append(f"### {m}: {MEASURES[m][0]}\n")
        tab = []
        for p in (data.ARMS["B"], data.ARMS["R"], data.NEVER):
            r = {"policy": label.get(p, p)}
            for ds in data.DATASETS:
                x = v[(v.measure == m) & (v.policy == p) & (v.dataset == ds)].iloc[0]
                r[SHORT[ds]] = (
                    "n/a" if np.isnan(x.value) else f"{x.value:.3f} [{x.lo:.3f}, {x.hi:.3f}]"
                )
            tab.append(r)
        s.append(md(pd.DataFrame(tab)) + "\n")
    s.append(
        "Full tables (every measure, policy, dataset and difference): `docs/paper1_eqsdp/tables/measure_values.csv`, `measure_diffs_B.csv`, `measure_diffs_R.csv`.\n"
    )
    return "\n".join(s)


def main():
    DOCS.mkdir(parents=True, exist_ok=True)
    TAB.mkdir(parents=True, exist_ok=True)
    for n in ["matrix_per_dataset", "matrix_pooled", "matrix_geq_counts"]:
        pd.read_csv(OUT / f"{n}.csv").to_csv(TAB / f"{n}.csv", index=False, float_format="%.5g")
    pd.read_csv(OUT / "measure_values.csv").to_csv(
        TAB / "measure_values.csv", index=False, float_format="%.4g"
    )
    dif = pd.read_csv(OUT / "measure_diffs.csv")
    for arm in ("B", "R"):
        dif[dif.arm == arm].drop(columns="arm").to_csv(
            TAB / f"measure_diffs_{arm}.csv", index=False, float_format="%.4g"
        )
    (DOCS / "02_COMPARISON_MATRIX.md").write_text(matrix_doc(), encoding="utf-8")
    (DOCS / "03_MEASURE_RESULTS.md").write_text(measure_doc(), encoding="utf-8")
    for p in TAB.glob("*.csv"):
        assert p.stat().st_size < 1_000_000, p
    print("docs written")


if __name__ == "__main__":
    main()
