RUNNER_SOURCE = """\
import importlib.abc
import importlib.util
import json
import os
import sys
import traceback

PACKET = os.path.dirname(os.path.abspath(__file__))
GUARD_SOURCE = @GUARD_SOURCE@
sys.path = [p for p in sys.path if not os.path.isdir(os.path.join(p or ".", "shiftlab"))]
sys.path.insert(0, PACKET)


class _Block(importlib.abc.MetaPathFinder):
    def find_spec(self, name, path, target=None):
        if name == "shiftlab" or name.startswith("shiftlab."):
            raise ImportError("shiftlab is not available inside the sandbox: " + name)
        return None


sys.meta_path.insert(0, _Block())
_out = sys.stdout
sys.stdout = sys.stderr  # adapter prints must not corrupt the protocol


def send(obj):
    _out.write(json.dumps(obj) + "\\n")
    _out.flush()


try:
    import numpy as np
    import interface

    # Preload what numeric adapters need so their imports never touch the guard, then forget
    # ctypes so that an adapter importing it triggers an audited (and denied) import.
    for _name in ("scipy.special", "scipy.stats", "scipy.optimize", "scipy.linalg"):
        try:
            __import__(_name)
        except ImportError:
            pass
    for _name in [
        m for m in sys.modules if m.split(".")[0] in ("ctypes", "_ctypes", "cffi", "gc", "inspect")
    ]:
        del sys.modules[_name]
    import builtins

    # Private copy of builtins: patching the real module cannot change what the hook calls.
    _guard_ns = {'__builtins__': dict(vars(builtins))}
    exec(compile(GUARD_SOURCE, '<guard>', 'exec'), _guard_ns)
    sys.addaudithook(_guard_ns['hook'])
    del _guard_ns, GUARD_SOURCE, builtins

    spec = importlib.util.spec_from_file_location("adapter", os.path.join(PACKET, ADAPTER_NAME))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    monitor = module.build_monitor()
    send({"ready": True})
except BaseException:
    send({"error": traceback.format_exc()})
    sys.exit(1)


def make_event(d):
    d = dict(d)
    d["x"] = np.asarray(d["x"], dtype=float)
    return interface.PublicEvent(**d)


for line in sys.stdin:
    try:
        msg = json.loads(line)
        op = msg["op"]
        if op == "reset":
            s = dict(msg["spec"])
            s["price_range"] = tuple(s["price_range"])
            monitor.reset(interface.TaskSpec(**s))
            send({"ok": True})
        elif op == "propensity":
            send({"q": float(monitor.propensity(make_event(msg["event"])))})
        elif op == "observe":
            fb = msg["feedback"]
            fb = None if fb is None else interface.Feedback(**fb)
            monitor.observe(make_event(msg["event"]), fb)
            send({"log_e": float(monitor.log_e_value)})
        elif op == "close":
            break
        else:
            send({"error": "unknown op " + repr(op)})
    except BaseException:
        send({"error": traceback.format_exc()})
"""


GUARD_TEMPLATE = """\
def hook(event, args):
    if (
        event == "open"
        or event == "import"
        or event in @PATH_EVENTS@
        or event in @MUTATION_EVENTS@
        or event.startswith("glob.")
    ):
        def norm(p):
            if not isinstance(p, str):
                if not isinstance(p, bytes):
                    p = p.__fspath__()
                if isinstance(p, bytes):
                    p = p.decode("utf-8", "surrogateescape")
            p = p.replace(@ALTSEP@, @SEP@)
            if @FOLD@:
                p = p.lower()
            if @WINDOWS@:
                if len(p) > 1 and p[1] == ":":
                    if len(p) < 3 or p[2] != @SEP@:
                        return None
                elif p[:1] == @SEP@:
                    return None
                else:
                    p = @PACKET@ + @SEP@ + p
            elif p[:1] != @SEP@:
                p = @PACKET@ + @SEP@ + p
            out = []
            for part in p.split(@SEP@):
                if part == "" or part == ".":
                    continue
                if part == "..":
                    if out:
                        out.pop()
                else:
                    out.append(part)
            return (@SEP@ if not @WINDOWS@ else "") + @SEP@.join(out)

        def inside(n, roots):
            if n is None:
                return False
            for r in roots:
                if n == r or n.startswith(r + @SEP@):
                    return True
            return False

        if event == "open":
            p = args[0]
            if p is None or isinstance(p, int):
                return
            n = norm(p)
            if inside(n, @PACKET_ROOTS@):
                return
            mode = args[1] if len(args) > 1 and isinstance(args[1], str) else "r"
            flags = args[2] if len(args) > 2 and isinstance(args[2], int) else 0
            writing = "w" in mode or "a" in mode or "x" in mode or "+" in mode
            if not writing and not flags & @WRITE_FLAGS@ and inside(n, @STD_ROOTS@):
                return
            raise PermissionError("sandbox audit guard denied: open " + str(p))
        if event == "import":
            name = args[0]
            if name.split(".")[0] in @BLOCKED_MODULES@:
                raise PermissionError("sandbox audit guard denied: import " + name)
            f = args[1] if len(args) > 1 else None
            if f is not None and not inside(norm(f), @ALL_ROOTS@):
                raise PermissionError("sandbox audit guard denied: import from " + str(f))
            return
        if event in @MUTATION_EVENTS@:
            for p in args[:2]:
                if isinstance(p, (str, bytes)) or hasattr(p, "__fspath__"):
                    if not inside(norm(p), @PACKET_ROOTS@):
                        raise PermissionError("sandbox audit guard denied: " + event + " " + str(p))
            return
        p = args[0] if args else None
        if p is None or isinstance(p, int):
            return
        if not inside(norm(p), @ALL_ROOTS@):
            raise PermissionError("sandbox audit guard denied: " + event + " " + str(p))
        return
    if event in @DENY_EVENTS@ or event.startswith(@DENY_PREFIXES@):
        raise PermissionError("sandbox audit guard denied: " + event)
    if event == "object.__setattr__" or event == "object.__delattr__":
        target = type(args[0]).__name__
        name = args[1] if len(args) > 1 else None
        value = type(args[2]).__name__ if len(args) > 2 else None
        if name in @TAMPER_NAMES@ or target in ("code", "cell", "frame") or (
            target == "module" and value != "module"
        ):
            raise PermissionError("sandbox audit guard denied: " + event + " " + str(name))
"""

_PATH_EVENTS = ("os.listdir", "os.scandir")
_MUTATION_EVENTS = (
    "os.remove",
    "os.rmdir",
    "os.mkdir",
    "os.rename",
    "os.chmod",
    "os.chown",
    "os.truncate",
    "os.utime",
)
_DENY_EVENTS = (
    "os.system",
    "os.posix_spawn",
    "os.fork",
    "os.forkpty",
    "os.startfile",
    "os.chdir",
    "os.symlink",
    "os.link",
    "os.mkfifo",
    "os.mknod",
    "gc.get_objects",
    "gc.get_referrers",
    "gc.get_referents",
    "sys._getframe",
    "sys._current_frames",
    "sys._current_exceptions",
    "sys.settrace",
    "sys.setprofile",
    "builtins.input",
)
_DENY_PREFIXES = (
    "subprocess.",
    "socket.",
    "ctypes.",
    "os.exec",
    "os.spawn",
    "function.",
    "code.",
    "cell.",
)
_BLOCKED_MODULES = ("ctypes", "_ctypes", "cffi", "_cffi_backend", "gc", "inspect")
_TAMPER_NAMES = (
    "__code__",
    "__closure__",
    "__globals__",
    "__defaults__",
    "__kwdefaults__",
    "__builtins__",
    "cell_contents",
)


def _guard_root(path: str) -> str:
    """Normalise a root the same way the generated hook normalises a path (strings only)."""
    p = os.path.realpath(path) if path else path
    return _guard_form(p)


def _guard_form(path: str) -> str:
    p = path.replace(os.altsep, os.sep) if os.altsep else path
    if os.name == "nt":
        p = p.lower()
    parts = [x for x in p.split(os.sep) if x not in ("", ".")]
    return ("" if os.name == "nt" else os.sep) + os.sep.join(parts)


def guard_source(packet: str | Path) -> str:
    """Return the audit-hook source with every allowlist embedded as a literal constant.

    The hook is stateless: the allowed roots live only in the code object's constants (no
    closure, no defaults, no global lookups for the allowlist) and path checks are pure string
    operations, so nothing the adapter can rebind changes what is allowed.
    """
    packet_forms = {_guard_root(str(packet)), _guard_form(str(Path(packet).absolute()))}
    std = set()
    for root in {sys.prefix, sys.base_prefix, sys.exec_prefix, sys.base_exec_prefix}:
        std.add(_guard_root(root))
        std.add(_guard_form(os.path.abspath(root)))
    packet_roots = tuple(sorted(packet_forms))
    std_roots = tuple(sorted(std))
    fields = {
        "PATH_EVENTS": _PATH_EVENTS,
        "MUTATION_EVENTS": _MUTATION_EVENTS,
        "DENY_EVENTS": _DENY_EVENTS,
        "DENY_PREFIXES": _DENY_PREFIXES,
        "BLOCKED_MODULES": _BLOCKED_MODULES,
        "TAMPER_NAMES": _TAMPER_NAMES,
        "PACKET_ROOTS": packet_roots,
        "STD_ROOTS": std_roots,
        "ALL_ROOTS": packet_roots + std_roots,
        "PACKET": _guard_root(str(packet)),
        "SEP": os.sep,
        "ALTSEP": os.altsep or os.sep,
        "FOLD": os.name == "nt",
        "WINDOWS": os.name == "nt",
        "WRITE_FLAGS": os.O_WRONLY | os.O_RDWR | os.O_APPEND | os.O_CREAT | os.O_TRUNC,
    }
    source = GUARD_TEMPLATE
    for key, value in fields.items():
        source = source.replace(f"@{key}@", repr(value))
    return source


class SandboxError(RuntimeError):
    """The sandboxed adapter failed, timed out or exited."""


def build_packet(adapter_path: str | Path, dest: str | Path, docs: tuple[Path, ...] | None = None):
    """Create the implementation packet in ``dest`` and return the adapter file name."""
    adapter = Path(adapter_path)
    root = Path(dest)
    root.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(Path(__file__).with_name("interface.py"), root / "interface.py")
    shutil.copyfile(adapter, root / adapter.name)
    (root / "_runner.py").write_text(
        RUNNER_SOURCE.replace("ADAPTER_NAME", repr(adapter.name)).replace(
            "@GUARD_SOURCE@", repr(guard_source(root))
        ),
        encoding="utf-8",
    )
    repo = Path(__file__).resolve().parents[3]
    doc_files = docs if docs is not None else tuple(repo / p for p in DOC_PATHS)
    (root / "docs").mkdir(exist_ok=True)
    for doc in doc_files:
        if Path(doc).exists():
            shutil.copyfile(doc, root / "docs" / Path(doc).name)
    return adapter.name


def packet_manifest(packet: str | Path) -> dict[str, str]:
    """SHA-256 of every packet file, keyed by posix relative path (for provenance)."""
    root = Path(packet)
    return {
        p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(root.rglob("*"))
        if p.is_file() and "__pycache__" not in p.parts
    }


def _stripped_env() -> dict[str, str]:
    keep = ("SYSTEMROOT", "SYSTEMDRIVE", "TEMP", "TMP")  # needed to start Python on Windows
    env = {k: os.environ[k] for k in keep if k in os.environ}
    env["PYTHONIOENCODING"] = "utf-8"
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    return env


class SandboxedMonitor:
    """A ``Monitor`` proxy that runs the adapter in an isolated subprocess."""

    def __init__(self, adapter_path: str | Path, *, timeout: float = 60.0, docs=None) -> None:
        self._tmp = tempfile.TemporaryDirectory(prefix="shiftlab_packet_")
        self.packet = Path(self._tmp.name)
        name = build_packet(adapter_path, self.packet, docs)
        self.manifest = packet_manifest(self.packet)
        self._timeout = timeout
        self._log_e = 0.0
        self._lines: queue.Queue[str | None] = queue.Queue()
        self._proc = subprocess.Popen(
            [sys.executable, "-I", str(self.packet / "_runner.py")],
            cwd=self.packet,
            env=_stripped_env(),
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            bufsize=1,
        )
        threading.Thread(target=self._pump, daemon=True).start()
        try:
            if self._read().get("ready") is not True:
                raise SandboxError("adapter did not report ready")
        except BaseException:
            self.close()
            raise
        self.adapter_name = name

    def _pump(self) -> None:
        assert self._proc.stdout is not None
        for line in self._proc.stdout:
            self._lines.put(line)
        self._lines.put(None)

    def _read(self) -> dict:
        try:
            line = self._lines.get(timeout=self._timeout)
        except queue.Empty:
            self._proc.kill()
            raise SandboxError("adapter timed out") from None
        if line is None:
            raise SandboxError("adapter process exited")
        reply = json.loads(line)
        if "error" in reply:
            raise SandboxError(reply["error"])
        return reply

    def _call(self, message: dict) -> dict:
        assert self._proc.stdin is not None
        self._proc.stdin.write(json.dumps(message) + "\n")
        self._proc.stdin.flush()
        return self._read()

    @staticmethod
    def _event(event: PublicEvent) -> dict:
        data = asdict(event)
        data["x"] = [float(v) for v in event.x]
        return data

    def reset(self, spec: TaskSpec) -> None:
        self._log_e = 0.0
        self._call({"op": "reset", "spec": asdict(spec)})

    def propensity(self, event: PublicEvent) -> float:
        return float(self._call({"op": "propensity", "event": self._event(event)})["q"])

    def observe(self, event: PublicEvent, feedback: Feedback | None) -> None:
        reply = self._call(
            {
                "op": "observe",
                "event": self._event(event),
                "feedback": None if feedback is None else asdict(feedback),
            }
        )
        self._log_e = float(reply["log_e"])

    @property
    def log_e_value(self) -> float:
        return self._log_e

    def close(self) -> None:
        if self._proc.poll() is None:
            try:
                assert self._proc.stdin is not None
                self._proc.stdin.write(json.dumps({"op": "close"}) + "\n")
                self._proc.stdin.flush()
                self._proc.wait(timeout=5)
            except (OSError, subprocess.SubprocessError):
                self._proc.kill()
        try:
            self._proc.wait(timeout=5)
        finally:
            for stream in (self._proc.stdin, self._proc.stdout):
                if stream is not None:
                    try:
                        stream.close()
                    except OSError:
                        pass
            self._tmp.cleanup()

    def __enter__(self) -> Self:
        return self

    def __exit__(self, *exc) -> None:
        self.close()
